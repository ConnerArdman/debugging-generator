#!/usr/bin/env node
/**
 * build-tokens — generate this package's design-token stylesheet.
 *
 *   input   src/tokens/tokens.ts    authored; the single source of truth
 *   output  src/tokens/tokens.css   generated; committed; never hand-edited
 *
 * The token source is the only place a visual value may be written, and this
 * script is the only writer of the stylesheet that projects those values into
 * CSS custom properties. So the generator holds no token name and no token
 * value of its own, never reads the stylesheet to decide what to emit, and
 * fails loudly instead of emitting a partial file.
 *
 * The contract with `src/tokens/tokens.ts`:
 *
 *   1. it exports `tokens` (or a default export) as a flat object of the value
 *      sets named in {@link THEME_BLOCKS} — `dark`, `light`, `highContrast` —
 *      each mapping the same token names to non-empty string (or finite
 *      numeric) values, units included in the string (`"2px"`, not `2`) and
 *      alias tokens written as `var(--dg-…)` strings;
 *   2. it uses erasable TypeScript syntax only and carries no relative runtime
 *      imports, because this generator imports it and lets the runtime strip
 *      its types (see {@link loadFailureHint} for each failure).
 *
 * Key order in the `dark` set is the stylesheet's declaration order, and every
 * block repeats that one order so the three blocks diff line by line.
 *
 * The contract with `src/tokens/tokens.css`: it is written here, excluded from
 * Prettier and ESLint, compared byte-wise against a fresh regeneration by
 * `src/tokens/tokens.test.ts`, and concatenated first into `dist/styles.css` by
 * `tsup.config.ts`, whose build stops when it is missing. These bytes are
 * therefore final — nothing reformats them, and volatile content of any kind (a
 * timestamp, a version, a hash, an absolute path) would make the drift test a
 * coin flip. There is none.
 *
 * Usage: `node scripts/build-tokens.mjs [--check]`, or `--help`. Importing this
 * module reads and writes nothing; only the entry point at the bottom acts.
 *
 * @module packages/panel-renderer/scripts/build-tokens
 */

import { realpathSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';

/**
 * This package's directory, from this module's own location rather than
 * `process.cwd()`: pnpm runs `prebuild` with the workspace as cwd, developers
 * run the script from the repository root and tests import it from a worker.
 */
export const PACKAGE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Package-relative path of the authored token source. */
export const TOKENS_SOURCE_REL = 'src/tokens/tokens.ts';

/** Package-relative path of the generated stylesheet. */
export const TOKENS_OUTPUT_REL = 'src/tokens/tokens.css';

/** The command that reconciles the stylesheet, quoted in every failure. */
const REGENERATE_COMMAND = 'node scripts/build-tokens.mjs';

/** In sync. */
const EXIT_OK = 0;

/** Drift, or a token source that cannot be serialised. */
const EXIT_DRIFT = 1;

/** Bad usage, an unloadable token source, or an I/O failure. */
const EXIT_ERROR = 2;

/**
 * The selector blocks, in the one order the stylesheet carries them: the
 * default theme as `:root`, then one attribute-scoped block per alternate
 * theme, double-quoted exactly as the token test builds each selector from
 * `PANEL_THEME_ATTRIBUTE_VALUES` in `src/tokens/theme.ts`. This table is the
 * generator's whole notion of "theme".
 *
 * @type {ReadonlyArray<{ readonly set: string, readonly selector: string }>}
 */
export const THEME_BLOCKS = Object.freeze([
  Object.freeze({ set: 'dark', selector: ':root' }),
  Object.freeze({ set: 'light', selector: '[data-theme="light"]' }),
  Object.freeze({ set: 'highContrast', selector: '[data-theme="high-contrast"]' }),
]);

/** Set whose key list and key order are canonical for every block. */
const CANONICAL = 'dark';

/** First line of the stylesheet. Fixed text, package-relative paths only. */
const HEADER =
  '/* Generated by scripts/build-tokens.mjs from src/tokens/tokens.ts — do not edit. */';

/** A complete custom property name this design system may declare. */
const CUSTOM_PROPERTY = /^--dg-[a-z0-9]+(-[a-z0-9]+)*$/u;

/** A bare token name {@link toCssPropertyName} can convert. */
const BARE_NAME = /^[A-Za-z][A-Za-z0-9]*(-[A-Za-z0-9]+)*$/u;

/** Findings printed before the report summarises the rest. */
const MAX_REPORTED_FINDINGS = 20;

/** Longest quoted line fragment a drift message prints. */
const MAX_QUOTED_LENGTH = 80;

/**
 * One mechanical problem with the token source.
 *
 * @typedef {object} TokenFinding
 * @property {string} rule stable rule id, printed in the report
 * @property {string} message single-line description
 * @property {string} set value set the finding belongs to
 * @property {string} [key] token key the finding belongs to
 */

/**
 * The token source is unusable. Carries every finding so a caller — the drift
 * test included — can assert on rule ids rather than on printed text.
 */
export class TokenValidationError extends Error {
  /** @param {readonly TokenFinding[]} findings every finding, in report order */
  constructor(findings) {
    const noun = findings.length === 1 ? 'finding' : 'findings';
    super(`${TOKENS_SOURCE_REL}: ${findings.length} token validation ${noun}`);
    this.name = 'TokenValidationError';
    /** @type {readonly TokenFinding[]} */
    this.findings = findings;
  }
}

/**
 * A failure reported as exit 2: bad usage, an unloadable token source or an I/O
 * error. Distinct from {@link TokenValidationError} (exit 1), whose fix is in
 * the token source rather than in the environment.
 */
class BuildTokensError extends Error {
  /**
   * @param {string} message single-line description
   * @param {{ hint?: string, showUsage?: boolean }} [options] recovery detail
   */
  constructor(message, options = {}) {
    super(message);
    this.name = 'BuildTokensError';
    /** @type {string | undefined} */
    this.hint = options.hint;
    /** @type {boolean} */
    this.showUsage = options.showUsage === true;
  }
}

/**
 * Build one finding.
 *
 * @param {string} rule
 * @param {string} set
 * @param {string | undefined} key
 * @param {string} message
 * @returns {TokenFinding}
 */
function finding(rule, set, key, message) {
  return key === undefined ? { rule, set, message } : { rule, set, key, message };
}

/**
 * Whether a value is a plain object usable as a flat token record; arrays and
 * class instances are not, because the authoring shape is an object literal.
 *
 * @param {unknown} value
 * @returns {boolean}
 */
function isPlainObject(value) {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return false;
  const prototype = Object.getPrototypeOf(value);
  return prototype === Object.prototype || prototype === null;
}

/**
 * The custom property name a token key is emitted as.
 *
 * A key that already is a complete `--dg-*` name comes back verbatim — the
 * primary contract, under which this generator is a pure serialiser. As a
 * documented accommodation a bare camelCase or kebab-case name is converted
 * (`surfaceBase` → `--dg-surface-base`, `space0` → `--dg-space-0`) by inserting
 * a boundary before each uppercase letter and before each digit that follows a
 * letter, then lowercasing; the digit boundary is what a plain camel-to-kebab
 * rule gets wrong. This is the only implementation of that mapping, and the
 * token source exposes the same conversion to TypeScript callers, so a change
 * here is a change there in the same commit.
 *
 * @param {string} key token key as authored
 * @returns {string} CSS custom property name
 */
export function toCssPropertyName(key) {
  if (CUSTOM_PROPERTY.test(key)) return key;
  const kebab = key.replace(/([A-Z])/gu, '-$1').replace(/([A-Za-z])(\d)/gu, '$1-$2');
  return `--dg-${kebab.toLowerCase()}`;
}

/**
 * Which convention a key follows: an explicit property name, a bare name that
 * converts to one, or neither.
 *
 * @param {string} key
 * @returns {'property' | 'bare' | 'invalid'}
 */
function classifyKey(key) {
  if (key.startsWith('--')) return CUSTOM_PROPERTY.test(key) ? 'property' : 'invalid';
  if (BARE_NAME.test(key) && CUSTOM_PROPERTY.test(toCssPropertyName(key))) return 'bare';
  return 'invalid';
}

/**
 * Name an unusable value without serialising it: an object value may be cyclic,
 * and its type is the point rather than its contents.
 *
 * @param {unknown} value
 * @returns {string}
 */
function describeValue(value) {
  if (value === null) return 'null';
  if (value === undefined) return 'no value';
  if (Array.isArray(value)) return 'an array';
  if (typeof value === 'number') return `the non-finite number ${String(value)}`;
  if (typeof value === 'boolean') return `the boolean ${String(value)}`;
  if (typeof value === 'object') return 'a nested object';
  return `a value of type ${typeof value}`;
}

/**
 * The clause a nested value earns. It is the one rejected shape that looks like
 * a design decision rather than a mistake, so the message says what the
 * authoring shape is and what changing it would cost.
 *
 * @param {unknown} value
 * @returns {string}
 */
function flatnessNote(value) {
  if (!isPlainObject(value) && !Array.isArray(value)) return '';
  return ' — a value set stays flat, so a different authoring shape means updating scripts/build-tokens.mjs in the same commit';
}

/**
 * Check one value set: key convention, key collisions, value types, keys the
 * canonical set does not declare, and — for an alternate theme — every
 * canonical key it fails to declare. Findings come out in the set's own key
 * order, then the convention check, then completeness in canonical key order.
 *
 * @param {string} set name of the value set
 * @param {Record<string, unknown>} values the set itself
 * @param {readonly string[] | undefined} canonicalKeys canonical key list, or
 *   `undefined` when this set is the canonical one
 * @returns {TokenFinding[]}
 */
function validateSet(set, values, canonicalKeys) {
  /** @type {TokenFinding[]} */
  const found = [];
  const canonical = canonicalKeys === undefined ? undefined : new Set(canonicalKeys);
  /** @type {Map<string, string>} property name → the key that claimed it */
  const claimed = new Map();
  /** @type {Partial<Record<'property' | 'bare', string>>} first key per style */
  const styles = {};

  for (const key of Object.keys(values)) {
    const at = `"${key}" in the "${set}" set`;
    const style = classifyKey(key);

    if (style === 'invalid') {
      const message = `${at} is neither a --dg-* property name nor a convertible bare name`;
      found.push(finding('token-key', set, key, message));
      continue;
    }

    styles[style] ??= key;

    const property = toCssPropertyName(key);
    const previous = claimed.get(property);
    if (previous === undefined) claimed.set(property, key);
    else
      found.push(
        finding('token-duplicate', set, key, `${at} names ${property}, as "${previous}" does`),
      );

    if (canonical !== undefined && !canonical.has(key)) {
      const message = `${at} is absent from the canonical "${CANONICAL}" set`;
      found.push(finding('token-unknown-in-theme', set, key, message));
    }

    const value = values[key];
    const usable = typeof value === 'number' ? Number.isFinite(value) : typeof value === 'string';
    if (typeof value === 'string' && value.trim() === '') {
      found.push(finding('token-empty', set, key, `${at} has an empty value`));
    } else if (!usable) {
      const wanted = 'a non-empty string (units included) or a finite number';
      const why = `${at} holds ${describeValue(value)}; expected ${wanted}${flatnessNote(value)}`;
      found.push(finding('token-value', set, key, why));
    }
  }

  if (styles.property !== undefined && styles.bare !== undefined) {
    const mixed = `the "${set}" set mixes conventions: "${styles.property}" is a --dg-* property name, "${styles.bare}" is a bare name`;
    found.push(finding('token-key', set, undefined, mixed));
  }

  for (const key of canonicalKeys ?? []) {
    if (Object.hasOwn(values, key)) continue;
    const message = `"${key}" is declared in "${CANONICAL}" but has no value in the "${set}" set`;
    found.push(finding('token-missing-in-theme', set, key, message));
  }

  return found;
}

/**
 * Every mechanical problem with a token table, in report order: value sets in
 * {@link THEME_BLOCKS} order, and within a set the order {@link validateSet}
 * describes. An empty array means the table can be serialised.
 *
 * Deliberately mechanical — no contrast computation, no accessibility check, no
 * sorting, no judgement about which themes ought to differ. Those assertions
 * belong to `src/tokens/tokens.test.ts`; this function covers only what would
 * produce a broken stylesheet.
 *
 * @param {unknown} tokens the loaded token table
 * @returns {TokenFinding[]}
 */
export function validateTokens(tokens) {
  /** @type {TokenFinding[]} */
  const found = [];
  const table = /** @type {Record<string, unknown>} */ (isPlainObject(tokens) ? tokens : {});
  const sets = THEME_BLOCKS.map((block) => block.set);

  for (const set of sets) {
    if (isPlainObject(table[set])) continue;
    const message = `the "${set}" value set is missing or is not a flat object; the token source declares one set per theme (${sets.join(', ')})`;
    found.push(finding('token-set-missing', set, undefined, message));
  }

  const canonicalValues = table[CANONICAL];
  if (!isPlainObject(canonicalValues)) return found;
  const canonicalKeys = Object.keys(/** @type {Record<string, unknown>} */ (canonicalValues));

  for (const set of sets) {
    const values = /** @type {Record<string, unknown> | undefined} */ (table[set]);
    if (values === undefined || !isPlainObject(values)) continue;
    found.push(...validateSet(set, values, set === CANONICAL ? undefined : canonicalKeys));
  }

  return found;
}

/**
 * The exact text of `src/tokens/tokens.css` for a token table.
 *
 * Pure: no filesystem, no environment, no cache, so one table always yields one
 * string — which is what lets the drift test compare bytes. Validation runs
 * first and throws, because a stylesheet missing a property in one theme
 * silently inherits the default theme's value and reads as a design bug rather
 * than a generation failure.
 *
 * @param {unknown} tokens the token table
 * @returns {string} the stylesheet, ending in exactly one newline
 * @throws {TokenValidationError} when the table cannot be serialised
 */
export function renderTokensCss(tokens) {
  const found = validateTokens(tokens);
  if (found.length > 0) throw new TokenValidationError(found);

  const table = /** @type {Record<string, Record<string, string | number>>} */ (tokens);
  const keys = Object.keys(table[CANONICAL] ?? {});

  const blocks = THEME_BLOCKS.map(({ set, selector }) => {
    const values = table[set] ?? {};
    const declarations = keys.map((key) => `  ${toCssPropertyName(key)}: ${String(values[key])};`);
    return [`${selector} {`, ...declarations, '}'].join('\n');
  });

  return `${HEADER}\n\n${blocks.join('\n\n')}\n`;
}

/**
 * The `code` property of a thrown value, when it has a string one.
 *
 * @param {unknown} error
 * @returns {string | undefined}
 */
function errorCode(error) {
  if (typeof error !== 'object' || error === null || !('code' in error)) return undefined;
  const { code } = /** @type {{ code?: unknown }} */ (error);
  return typeof code === 'string' ? code : undefined;
}

/**
 * A thrown value's message, for a single-line report.
 *
 * @param {unknown} error
 * @returns {string}
 */
function errorMessage(error) {
  return error instanceof Error ? error.message : String(error);
}

/**
 * What a load failure means and how to recover. The first line is keyed on the
 * runtime's own error code — the three this contract can produce, then a
 * generic line — and the rest states the erasable-syntax requirement and the
 * one documented escape hatch. That escape hatch is a pair of changes on
 * purpose: running the generator through a loader while the manifest still says
 * plain `node` leaves `prebuild` broken for everyone else.
 *
 * @param {string | undefined} code
 * @returns {string}
 */
function loadFailureHint(code) {
  /** @type {Record<string, string>} */
  const causes = {
    ERR_UNSUPPORTED_TYPESCRIPT_SYNTAX:
      'It uses TypeScript syntax the runtime cannot erase (an enum, a namespace, a constructor' +
      ' parameter property or a decorator).',
    ERR_MODULE_NOT_FOUND:
      'It imports a relative specifier the runtime cannot resolve — most likely an extensionless' +
      ' one, which only a bundler resolves. The token source carries no relative runtime imports.',
    ERR_UNKNOWN_FILE_EXTENSION:
      'This runtime did not strip the types of a TypeScript module; use the version pinned in' +
      ' .nvmrc / .node-version.',
  };

  return [
    causes[code ?? ''] ?? 'The module threw while loading.',
    '',
    `${TOKENS_SOURCE_REL} is imported directly and its types are stripped by the runtime, so it`,
    'must use erasable TypeScript syntax only — type annotations, `import type`, `as const`,',
    '`satisfies` — and must carry no relative runtime imports.',
    '',
    'If a token source ever genuinely needs more than that, run this generator under tsx:',
    '',
    '  pnpm exec tsx scripts/build-tokens.mjs',
    '',
    "and change this package's package.json `prebuild` script to the same command in the same",
    'commit, so the manifest and this script never disagree. Nothing was written.',
  ].join('\n');
}

/**
 * Import the token source and return its token table, read from the named
 * `tokens` export or, failing that, the default export.
 *
 * The module is imported, never parsed as text: a second reader of these values
 * would be a second source of truth, and the token source must be the only one.
 *
 * @param {{ root?: string }} [options] `root` overrides the package directory,
 *   which lets a test drive a temporary tree
 * @returns {Promise<unknown>} the token table, unvalidated
 * @throws {BuildTokensError} when the module cannot be loaded or exports none
 */
export async function loadTokens({ root = PACKAGE_ROOT } = {}) {
  const file = path.join(root, ...TOKENS_SOURCE_REL.split('/'));

  /** @type {Record<string, unknown>} */
  let loaded;
  try {
    loaded = await import(pathToFileURL(file).href);
  } catch (error) {
    const code = errorCode(error);
    const what = `could not be loaded (${code ?? 'no error code'}): ${errorMessage(error)}`;
    throw new BuildTokensError(`${TOKENS_SOURCE_REL}: ${what}`, { hint: loadFailureHint(code) });
  }

  const table = loaded.tokens ?? loaded.default;
  if (table !== undefined) return table;

  const hint = 'Export the token table as the named `tokens` export, or as the default export.';
  throw new BuildTokensError(`${TOKENS_SOURCE_REL}: exports no token table`, {
    hint: `${hint} Nothing was written.`,
  });
}

/**
 * Read a file, or `undefined` when it does not exist. Any other failure is an
 * exit-2 error naming the path: a stylesheet that cannot be read is an
 * environment problem, not drift.
 *
 * @param {string} file absolute path
 * @param {string} rel package-relative path, for the message
 * @returns {Promise<string | undefined>}
 */
async function readOptional(file, rel) {
  try {
    return await readFile(file, 'utf8');
  } catch (error) {
    if (errorCode(error) === 'ENOENT') return undefined;
    throw new BuildTokensError(`${rel}: could not be read: ${errorMessage(error)}`);
  }
}

/**
 * Quote one stylesheet line for a drift message, or name the end of the file
 * when that line does not exist. Long lines are elided at a fixed length, so
 * the message stays single-line and depends only on the content.
 *
 * @param {string | undefined} line
 * @returns {string}
 */
function quoteLine(line) {
  if (line === undefined) return 'end of file';
  const shown = line.length > MAX_QUOTED_LENGTH ? `${line.slice(0, MAX_QUOTED_LENGTH - 1)}…` : line;
  return `"${shown}"`;
}

/**
 * Describe the first difference between the generated stylesheet and the one on
 * disk: one line, non-volatile, with a 1-based line number. A file that differs
 * only in line endings is reported as such, since that is a checkout setting
 * rather than a token change.
 *
 * @param {string} expected freshly generated text
 * @param {string} actual text on disk
 * @returns {string}
 */
function describeDrift(expected, actual) {
  if (actual.replaceAll('\r\n', '\n') === expected) {
    return (
      `${TOKENS_OUTPUT_REL}: drift: the file on disk uses CRLF line endings and the generated` +
      ' stylesheet is LF-only (a CRLF checkout is the likely cause; see .editorconfig)'
    );
  }

  const expectedLines = expected.split('\n');
  const actualLines = actual.split('\n');
  const lineCount = Math.max(expectedLines.length, actualLines.length);

  for (let index = 0; index < lineCount; index += 1) {
    const want = expectedLines[index];
    const found = actualLines[index];
    if (want === found) continue;
    const at = `${TOKENS_OUTPUT_REL}:${index + 1}`;
    return `${at}: drift: expected ${quoteLine(want)} / found ${quoteLine(found)}`;
  }

  return `${TOKENS_OUTPUT_REL}: drift: the file on disk differs from the generated stylesheet`;
}

/**
 * Generate the stylesheet and write it only when its bytes would change, so
 * watchers and incremental builds see no modification. A failed render writes
 * nothing at all: the previous stylesheet survives a broken token source.
 *
 * @param {{ root?: string }} [options] `root` overrides the package directory
 * @returns {Promise<{ action: 'written' | 'unchanged', file: string, css: string }>}
 * @throws {TokenValidationError} when the token source cannot be serialised
 * @throws {BuildTokensError} when it cannot be loaded, or the write fails
 */
export async function writeTokensCss({ root = PACKAGE_ROOT } = {}) {
  const css = renderTokensCss(await loadTokens({ root }));
  const file = path.join(root, ...TOKENS_OUTPUT_REL.split('/'));
  const current = await readOptional(file, TOKENS_OUTPUT_REL);

  if (current === css) return { action: 'unchanged', file, css };

  try {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, css, 'utf8');
  } catch (error) {
    throw new BuildTokensError(
      `${TOKENS_OUTPUT_REL}: could not be written: ${errorMessage(error)}`,
    );
  }

  return { action: 'written', file, css };
}

/**
 * Compare the stylesheet on disk with a fresh generation, byte for byte, and
 * write nothing whatever the outcome.
 *
 * @param {{ root?: string }} [options] `root` overrides the package directory
 * @returns {Promise<{ status: 'unchanged' | 'missing' | 'drift', file: string, css: string, detail?: string }>}
 * @throws {TokenValidationError} when the token source cannot be serialised
 * @throws {BuildTokensError} when it cannot be loaded, or the read fails
 */
export async function checkTokensCss({ root = PACKAGE_ROOT } = {}) {
  const css = renderTokensCss(await loadTokens({ root }));
  const file = path.join(root, ...TOKENS_OUTPUT_REL.split('/'));
  const current = await readOptional(file, TOKENS_OUTPUT_REL);

  if (current === undefined) return { status: 'missing', file, css };
  if (current === css) return { status: 'unchanged', file, css };
  return { status: 'drift', file, css, detail: describeDrift(css, current) };
}

/**
 * Command-line usage, printed by `--help` and beside a usage error.
 *
 * @returns {string}
 */
function usage() {
  return `usage: ${REGENERATE_COMMAND} [--check]

Generates ${TOKENS_OUTPUT_REL} from ${TOKENS_SOURCE_REL}, this design system's
single token source. Both paths resolve from this script's own location, so the
result is identical from any working directory.

Options:
  --check      regenerate in memory and compare with the file on disk; writes
               nothing
  -h, --help   print this help and exit

Exit codes:
  0  the stylesheet was written, or was already up to date
  1  --check found drift, or the token source failed validation
  2  bad usage, an unloadable token source, or an I/O failure`;
}

/**
 * Parse the command line. The script takes no positional arguments, so an
 * unrecognised token is a usage error rather than something silently ignored.
 *
 * @param {readonly string[]} argv arguments after the script path
 * @returns {{ check: boolean, help: boolean }}
 * @throws {BuildTokensError} on an unrecognised argument
 */
function parseArgs(argv) {
  const args = { check: false, help: false };

  for (const arg of argv) {
    switch (arg) {
      case '--check':
        args.check = true;
        break;
      case '--help':
      case '-h':
        args.help = true;
        break;
      default:
        throw new BuildTokensError(`unrecognised argument: ${arg}`, { showUsage: true });
    }
  }

  return args;
}

/**
 * Write one line to a stream, instead of `console`, so output is exactly one
 * line per message and a caller can capture it.
 *
 * @param {import("node:stream").Writable} stream
 * @param {string} text
 * @returns {void}
 */
function writeLine(stream, text) {
  stream.write(`${text}\n`);
}

/**
 * Print a failure and return the exit code it maps to. Findings use the house
 * `path: rule-id: message` format, capped so a wholesale mistake in the token
 * source does not bury the first lines.
 *
 * @param {unknown} error
 * @param {import("node:stream").Writable} stream
 * @returns {number}
 */
function reportFailure(error, stream) {
  if (error instanceof TokenValidationError) {
    for (const item of error.findings.slice(0, MAX_REPORTED_FINDINGS)) {
      writeLine(stream, `${TOKENS_SOURCE_REL}: ${item.rule}: ${item.message}`);
    }
    const hidden = error.findings.length - MAX_REPORTED_FINDINGS;
    if (hidden > 0) writeLine(stream, `… and ${hidden} more`);
    writeLine(stream, `${TOKENS_OUTPUT_REL} was not written`);
    return EXIT_DRIFT;
  }

  if (error instanceof BuildTokensError) {
    writeLine(stream, error.message);
    if (error.hint !== undefined) writeLine(stream, `\n${error.hint}`);
    if (error.showUsage) writeLine(stream, `\n${usage()}`);
    return EXIT_ERROR;
  }

  const detail = error instanceof Error ? (error.stack ?? error.message) : String(error);
  writeLine(stream, `build-tokens: unexpected failure\n${detail}`);
  return EXIT_ERROR;
}

/**
 * Command-line entry point. Prints its own output and returns the exit code
 * instead of ending the process, so a caller can drive it and read the result.
 *
 * @param {readonly string[]} [argv] arguments after the script path
 * @param {{ root?: string, stdout?: import("node:stream").Writable, stderr?: import("node:stream").Writable }} [options]
 * @returns {Promise<number>} 0 in sync, 1 drift or invalid tokens, 2 failure
 */
export async function main(argv = [], options = {}) {
  const stdout = options.stdout ?? process.stdout;
  const stderr = options.stderr ?? process.stderr;
  const root = options.root ?? PACKAGE_ROOT;

  let args;
  try {
    args = parseArgs(argv);
  } catch (error) {
    return reportFailure(error, stderr);
  }

  if (args.help) {
    writeLine(stdout, usage());
    return EXIT_OK;
  }

  try {
    if (args.check) {
      const result = await checkTokensCss({ root });

      if (result.status === 'unchanged') {
        writeLine(stdout, `${TOKENS_OUTPUT_REL} is up to date`);
        return EXIT_OK;
      }

      if (result.status === 'missing') {
        writeLine(stderr, `${TOKENS_OUTPUT_REL}: missing: run "${REGENERATE_COMMAND}"`);
        return EXIT_DRIFT;
      }

      writeLine(stderr, result.detail ?? `${TOKENS_OUTPUT_REL}: drift`);
      writeLine(stderr, `fix: run "${REGENERATE_COMMAND}"`);
      return EXIT_DRIFT;
    }

    const { action } = await writeTokensCss({ root });
    const done =
      action === 'written' ? `wrote ${TOKENS_OUTPUT_REL}` : `${TOKENS_OUTPUT_REL} is up to date`;
    writeLine(stdout, done);
    return EXIT_OK;
  } catch (error) {
    return reportFailure(error, stderr);
  }
}

/**
 * Whether this module is the process entry point, so importing it — which
 * `src/tokens/tokens.test.ts` does — never runs the CLI. The entry path is
 * resolved through `realpath` because the runtime reports `import.meta.url` as
 * a real path, and a workspace reached through a symbolic link would otherwise
 * compare unequal.
 *
 * @returns {boolean}
 */
function isEntryPoint() {
  const entry = process.argv[1];
  if (entry === undefined || entry === '') return false;

  let resolved;
  try {
    resolved = realpathSync(entry);
  } catch {
    resolved = path.resolve(entry);
  }

  return import.meta.url === pathToFileURL(resolved).href;
}

if (isEntryPoint()) {
  // `process.exitCode` rather than `process.exit()`, so buffered output is
  // flushed before the process ends.
  process.exitCode = await main(process.argv.slice(2));
}
