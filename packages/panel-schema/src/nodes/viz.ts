/**
 * The thirteen visualization nodes a generated panel may compose, in their
 * normalized form.
 *
 * A panel is a document of nodes. `./layout.ts` contributes the three nodes that
 * only arrange other nodes; this module contributes every node that actually
 * draws something. Twelve of them draw a prepared view of the captured evidence,
 * named by the data query (`DataQuery` in `./query.ts`) they carry; the thirteenth draws a pointer into
 * the developer's own source. Together they are the entire vocabulary a
 * generated panel has for presenting a finding — which is exactly why they are
 * enumerated here rather than assembled ad hoc by whatever produces a panel.
 *
 * ## Why thirteen, and why they must differ from each other
 *
 * The product's claim is that two different debugging questions produce two
 * materially different panels rather than one template with a different title.
 * That claim is only true if the vocabulary is rich enough to be selective: a
 * latency question wants a correlated timeline, a hierarchical breakdown of where
 * the time went and the statements that dominated it, while a re-render question
 * wants per-component counts, the tree they sit in and the state transitions that
 * triggered them. The two panels overlap in the summary header, the metric tiles
 * and the source chips, and their bodies are otherwise disjoint. Every node below
 * earns its place by being the view some question needs and no other node
 * provides; a node type that could be replaced by another with a different filter
 * does not belong here.
 *
 * ## Every node here is a leaf
 *
 * No visualization node has children. Nesting belongs to the layout nodes, and
 * the node catalog records the distinction as a per-type flag, so this module
 * exports **concrete schemas** rather than the factories `./layout.ts` must
 * export: nothing below needs a reference to the not-yet-defined node union, and
 * the one place the recursion is closed is the parent folder's specification
 * module, which ties the layout factories and the tuple exported at the bottom of
 * this file into a single discriminated union. A schema here that reached for the
 * union would move that closure into this file and duplicate it.
 *
 * ## The type names are a four-place contract
 *
 * {@link VISUALIZATION_NODE_TYPES} is not an internal enumeration. The
 * specification module composes the panel's full type vocabulary from the layout
 * types plus these, the node catalog holds one entry per member — and its own
 * test asserts that the catalog's key set equals that composed vocabulary
 * exactly, all sixteen of it — and the shared renderer library keys its component
 * registry off the same names, with a test that fails on a catalog entry that has
 * no component. Adding a type here is therefore four coordinated changes: the
 * schema below, the catalog entry that declares which sources it may read and
 * which telemetry fields it reads, the renderer component, and the registry
 * binding. Renaming or dropping one is the same four changes plus every stored
 * panel that already names it. Prefer adding a member to repurposing one.
 *
 * ## What this module deliberately does not own
 *
 * Four questions about a node are answered elsewhere, and answering any of them
 * here would create the second source of truth that the other side's test exists
 * to prevent:
 *
 * - **Which sources a node type may read** is the node catalog's single registry,
 *   enforced by the syntactic validator. Nothing below constrains a node's
 *   `query` beyond requiring a well-formed one, and the `describe` text below
 *   orients rather than legislates precisely so the two cannot drift.
 * - **Whether ids are unique within a panel** is the syntactic validator's
 *   check, which is the only layer that sees the whole document. A node can only
 *   say that its own id is well-formed.
 * - **Whether the evidence a node points at exists** is semantic validation,
 *   which is the only layer that sees a capture.
 * - **Lifting a flat authoring field into `node.query`** is the deterministic
 *   normaliser's job. This module is the *result* of that lift and describes no
 *   flat field at all.
 *
 * ## Why no node carries a presentation option
 *
 * There is no `height`, no `columns`, no `lanes`, no `threshold` and no colour on
 * any node below, and their absence is a security property rather than an
 * omission. Every visual decision belongs to the shared renderer library, whose
 * components resolve every value to a design token; a panel is generated by a
 * model, so an option here would hand that model a channel for authoring
 * presentation, which is the one thing a generated specification must never carry.
 * What a node *may* vary is which evidence it draws — its `DataQuery` — and
 * nothing else. If a component genuinely needs a knob, it is added to the catalog
 * entry and the schema together, deliberately, and reviewed as the widening of a
 * model-writable surface that it is.
 *
 * ## Authoring form versus normalized form
 *
 * This module defines the **normalized** node: strict, with its identity assigned
 * and its data request nested under `query`. Only the normaliser produces it, and
 * only it may reach the renderer. The permissive authoring form a model writes
 * lives in the parent folder's input module and accepts the flat `source`,
 * `filter` and `sort` fields; keeping this form strict and nested is what lets the
 * authoring and normalisation tests prove a flat field was genuinely lifted rather
 * than quietly carried through. For the same reason nothing below carries a
 * `.default()`, a `.transform()` or a `.preprocess()`: a parsed node must equal
 * the node that was written, field for field, or a stored panel and a freshly
 * normalised one would differ by nothing but which version of this file parsed
 * them.
 *
 * ## Constraints every declaration below works under
 *
 * - **Environment-neutral.** This package is bundled with no platform
 *   assumptions, because the local service, the DevTools panel and the editor
 *   webview all load it. No `node:` builtin, no DOM global, and no import-time
 *   side effect: every export here is a frozen vocabulary, a schema, a type or a
 *   pure function.
 * - **JSON-Schema-representable.** The parent folder renders the authoring schema
 *   that mirrors these shapes into a versioned prompt file, configured to fail on
 *   anything it cannot represent. Every constraint below is declarative — a
 *   literal, an enumeration, an array bound — so the model reads the same limits
 *   the validator enforces, and there is no refinement to be silently dropped
 *   from the rendered document and returned later as a parse failure.
 * - **No second copy of another package's vocabulary.** The metric ids a metric
 *   tile may display are the telemetry package's fixed set, imported; the source
 *   location a source chip points at is the shared package's single definition,
 *   imported; the data query, the id and the two labels are `./query.ts`'s,
 *   imported. This module declares node shapes and nothing else.
 *
 * @example
 * ```ts
 * // One node of a normalized panel: what to draw, and what to draw it from.
 * const node = timelineNodeSchema.parse({
 *   type: 'timeline',
 *   id: 'layout.0.children.1',
 *   title: 'Where the time went',
 *   query: { source: 'trace', filter: { traceId } },
 * });
 * ```
 */

import { z } from 'zod';

import { sourceLocationSchema } from '@debuggen/shared';
import { METRIC_IDS } from '@debuggen/telemetry';

import {
  dataQuerySchema,
  panelNodeDescriptionSchema,
  panelNodeIdSchema,
  panelNodeTitleSchema,
} from './query.js';

/*
 * ---------------------------------------------------------------------------
 * Node-type vocabularies
 * ---------------------------------------------------------------------------
 */

/**
 * The twelve node types whose content is a prepared view of the capture, in the
 * order the panel DSL fixes.
 *
 * The order is part of the declaration rather than an accident of typing: it is
 * the order the rendered JSON Schema lists for the model and the order the
 * catalog is read in, and it runs from the views of one whole interaction
 * (timeline, waterfall, event log), through the computed summary (metric tiles)
 * and the breakdowns of a single dimension (hierarchical timing, span ranking,
 * render statistics, component tree), to the per-concern groupings (requests,
 * statements, state transitions) and finally the correlated flow as a graph.
 *
 * Every member of this tuple requires a data query; the source-link leaf
 * is the one visualization node that does not, which is why it is absent here and
 * appended once in {@link VISUALIZATION_NODE_TYPES}.
 *
 * Frozen: a read-only vocabulary shared by this package, the coordination service
 * and both user interfaces.
 */
export const QUERY_BACKED_NODE_TYPES = Object.freeze([
  /** One interaction on a shared time axis, in lanes by tier. */
  'timeline',
  /** Requests and their dependencies as offset bars, longest chain visible. */
  'waterfall',
  /** Every captured record as a chronological, filterable list. */
  'eventLog',
  /** The capture's computed headline numbers as tiles. */
  'metricCards',
  /** Nested timing as an icicle: which call held the time, and inside what. */
  'flame',
  /** A sortable ranking of spans — the "what took longest" table. */
  'table',
  /** Per-component render counts, timing and trigger attribution. */
  'renderTable',
  /** The component tree with each node's render count. */
  'componentTree',
  /** Network calls grouped so repeats collide, with duplicate counts. */
  'requestTable',
  /** Database statements grouped by parameterized text, with their callers. */
  'queryTable',
  /** Hook state changes as from-trigger-to rows. */
  'stateTransitions',
  /** The correlated flow as nodes and edges across the tiers. */
  'dependencyGraph',
] as const);

/**
 * One member of the query-backed node vocabulary.
 *
 * Derived from {@link QUERY_BACKED_NODE_TYPES}, so the runtime tuple and the
 * static type cannot disagree. Useful wherever the distinction that matters is
 * "this node needs data fetched for it" — the host resolving queries, the
 * validator checking that a node which requires a query has one.
 */
export type QueryBackedNodeType = (typeof QUERY_BACKED_NODE_TYPES)[number];

/**
 * Every visualization node type: the twelve query-backed ones plus the
 * source-link leaf.
 *
 * Derived from {@link QUERY_BACKED_NODE_TYPES} rather than written out again, so
 * the twelve have exactly one declaration and the only thing this tuple adds is
 * the member that genuinely differs. The specification module composes the
 * panel's full type vocabulary from the layout types plus this tuple, and the
 * catalog's test asserts its key set equals that composition exactly — see the
 * module documentation above for the four places a change here has to reach.
 *
 * Frozen, for the same reason the tuple it extends is.
 */
export const VISUALIZATION_NODE_TYPES = Object.freeze([
  ...QUERY_BACKED_NODE_TYPES,
  /** A pointer into the developer's source, rendered as a clickable chip. */
  'sourceLink',
] as const);

/**
 * One member of the visualization node vocabulary.
 *
 * Derived from {@link VISUALIZATION_NODE_TYPES}. This is the type the catalog is
 * keyed by, the renderer's component registry is keyed by, and the discriminator
 * of {@link VisualizationNode}.
 */
export type VisualizationNodeType = (typeof VISUALIZATION_NODE_TYPES)[number];

/**
 * The visualization node type as a schema, described for the model that authors
 * one.
 *
 * Exported in its own right because a type name also travels on its own: a
 * catalog lookup validating a stored panel's node, a user-interface control
 * offering the vocabulary. The per-node schemas below each pin their own literal,
 * so this is not the gate a parsed node passes through — it is the gate for a
 * type name that arrived without its node.
 */
export const visualizationNodeTypeSchema = z
  .enum(VISUALIZATION_NODE_TYPES)
  .describe(
    'Which visualization a panel node draws. Twelve of these draw a prepared view of the captured evidence and therefore carry a data query; the source-link leaf instead carries one resolved source location and no query.',
  );

/** Widened view of {@link VISUALIZATION_NODE_TYPES} used by {@link isVisualizationNodeType}. */
const VISUALIZATION_NODE_TYPE_VALUES: readonly string[] = VISUALIZATION_NODE_TYPES;

/**
 * Narrow an untrusted value to a {@link VisualizationNodeType} by membership in
 * {@link VISUALIZATION_NODE_TYPES}.
 *
 * For the places that classify a node before a schema is available: a stored
 * panel row being read back, a node type arriving on its own rather than inside a
 * node. The per-node schemas are the primary gate; this predicate exists so that
 * no caller has to spell the vocabulary to ask the question.
 */
export function isVisualizationNodeType(value: unknown): value is VisualizationNodeType {
  return typeof value === 'string' && VISUALIZATION_NODE_TYPE_VALUES.includes(value);
}

/*
 * ---------------------------------------------------------------------------
 * Shared node shape
 *
 * The fields every node below has, declared once. Two shapes rather than one,
 * because the source-link leaf carries no data request: the base is the identity
 * and the two labels, and the query-backed shape is that base plus the required
 * query. Neither is exported — a caller wanting "any visualization node" wants
 * the union at the bottom of this file, not a half-shape it would have to
 * assemble.
 * ---------------------------------------------------------------------------
 */

/**
 * The identity and labels every visualization node carries.
 *
 * The primitives come from `./query.ts`, where `./layout.ts` takes them from too:
 * a field defined twice is a field whose two definitions diverge on the first
 * tightened bound. Identity is required, because this is the normalized form —
 * the normaliser derives an id from the node's position in the layout, and the
 * authoring schema rejects an authored one.
 */
const visualizationNodeShape = {
  /** This node's identity within the panel, assigned by the normaliser. */
  id: panelNodeIdSchema,

  /** Optional heading shown above the node. */
  title: panelNodeTitleSchema.optional(),

  /** Optional sentence shown under the heading. */
  description: panelNodeDescriptionSchema.optional(),
};

/**
 * The shape shared by the twelve query-backed nodes: identity, labels and the
 * required data request.
 *
 * `query` is required on every one of them, and required here rather than left
 * optional-and-checked-later on purpose: a node whose content is a view of the
 * capture has nothing to draw without one, so a missing query is a malformed
 * node rather than a node in a degraded state. The validator's own check that a
 * query-requiring node carries a query is the catalog-driven statement of the
 * same rule for the authoring form, where the field may still be absent before
 * normalisation lifts it.
 */
const queryBackedNodeShape = {
  ...visualizationNodeShape,

  /** Which prepared view of the capture this node draws, and how to narrow it. */
  query: dataQuerySchema.describe(
    'Which prepared view of the captured evidence this node draws, and how to narrow, order and page it. Required: this node type has nothing to draw without one. The node catalog states which sources this node type can read.',
  ),
};

/*
 * ---------------------------------------------------------------------------
 * The twelve query-backed nodes
 *
 * One `z.strictObject` each, all of them the shared shape above plus their own
 * `type` literal — and, for exactly one of them, one extra option. Strict is
 * load-bearing: an unrecognised key on a node is either a field this module
 * removed, in which case the panel was written against a contract that no longer
 * holds and must be regenerated rather than half-honoured, or a dimension its
 * author invented, which the renderer would ignore while the panel went on
 * claiming to show something it does not.
 *
 * The `type` literal is what the specification module's discriminated union keys
 * on, which is what makes a malformed node fail against one schema with one
 * clear issue path instead of against thirteen at once.
 * ---------------------------------------------------------------------------
 */

/**
 * One interaction laid out on a shared time axis, in lanes by tier.
 *
 * The cross-tier view: the browser work, the request it made, the server work it
 * reached and the datastore call at the bottom, all on one axis, so the handover
 * from each tier to the next is a visible gap rather than an inference. This is
 * the node a "why was this slow" panel opens with, and it is the only node that
 * shows the whole correlated shape of an interaction at once.
 */
export const timelineNodeSchema = z
  .strictObject({
    type: z.literal('timeline'),
    ...queryBackedNodeShape,
  })
  .describe(
    'A correlated timeline of one interaction: every span placed on a shared time axis, grouped into lanes by the tier that produced it, so the time each tier held and the gaps between them are directly visible. Suits a question about where the time in one interaction went. Narrow it to a single interaction, since a capture holds many. Selecting a span opens its detail; a span that resolved to a source location offers a link to it.',
  );

/** One interaction as cross-tier lanes on a shared time axis. */
export type TimelineNode = z.infer<typeof timelineNodeSchema>;

/**
 * Calls as offset bars ordered by when they started, with their nested work.
 *
 * The timeline's complement rather than a duplicate of it: a timeline answers
 * "which tier held the time", a waterfall answers "what was waiting on what".
 * Bars are positioned by offset from the first call, so serialisation that should
 * have been concurrent reads as a staircase and genuinely parallel work reads as
 * a block.
 */
export const waterfallNodeSchema = z
  .strictObject({
    type: z.literal('waterfall'),
    ...queryBackedNodeShape,
  })
  .describe(
    'A waterfall of the calls in one interaction: each call a bar positioned by its offset from the first, with the work nested beneath it expandable. Suits a question about ordering and overlap — work that ran one after another when it could have run together appears as a staircase. Narrow it to a single interaction.',
  );

/** Calls as offset bars with their nested work. */
export type WaterfallNode = z.infer<typeof waterfallNodeSchema>;

/**
 * Every captured record in order, as a filterable list.
 *
 * The view with no opinion: no grouping, no ranking, no aggregation, just what
 * happened and when. It is what a developer falls back to when the aggregated
 * views agree and the explanation is still missing, and it is virtualized because
 * a capture of a busy page is thousands of records long.
 */
export const eventLogNodeSchema = z
  .strictObject({
    type: z.literal('eventLog'),
    ...queryBackedNodeShape,
  })
  .describe(
    'A chronological log of captured records, filterable by kind and by text. Suits a question that needs raw sequence rather than a summary, or a panel that wants the unaggregated evidence behind the views above it. Narrow it by kind to keep it readable; selecting a row opens that record in full.',
  );

/** Captured records in chronological order. */
export type EventLogNode = z.infer<typeof eventLogNodeSchema>;

/**
 * The capture's headline numbers as tiles.
 *
 * Normalisation "gives `metricCards` the implicit `query: { source: "metrics" }`
 * with `metrics` kept as the node's option" — which is why `metrics` sits on the
 * node below and **must not be tidied into `query`**. The distinction is not
 * cosmetic: the renderer reads the id list from the node, the flat-field lift
 * deliberately excludes `metrics` from the fields it relocates, and a `metrics`
 * moved under `query` would leave the node rendering empty while still parsing.
 *
 * The ids themselves are the telemetry package's fixed set, imported rather than
 * restated, and both array bounds derive from that same tuple: at least one id,
 * because a tile row with no tiles is a mistake rather than an intent, and at
 * most as many as exist, because a longer list can only contain repeats.
 */
export const metricCardsNodeSchema = z
  .strictObject({
    type: z.literal('metricCards'),
    ...queryBackedNodeShape,

    /**
     * Which computed values to show, in the order they should be shown.
     *
     * A node option rather than a query field — see this schema's documentation
     * above for why that separation is load-bearing. Order is preserved as
     * written: the first id is the tile a developer reads first, so the author
     * chooses the emphasis rather than inheriting the order the metrics happen
     * to be computed in.
     */
    metrics: z
      .array(z.enum(METRIC_IDS))
      .min(1)
      .max(METRIC_IDS.length)
      .describe(
        `Which computed values of the capture to show as tiles, in display order. At least one and at most ${String(METRIC_IDS.length)} ids, each drawn from the fixed metric vocabulary. Choose the few that bear on the question rather than every available id: a value that is unavailable for this capture is shown as such, so asking for an irrelevant one costs a tile that says nothing.`,
      ),
  })
  .describe(
    'A row of tiles showing computed values of the capture — durations, counts and sizes — with the severity of each shown against the same thresholds everywhere in the product. Suits any panel that needs the headline numbers a finding is read against, which is why it is one of the few nodes that recurs across otherwise dissimilar panels. The ids to show are an option of this node, not part of its query.',
  );

/** Computed values of the capture, shown as tiles. */
export type MetricCardsNode = z.infer<typeof metricCardsNodeSchema>;

/**
 * Nested timing as an icicle: which call held the time, and inside what.
 *
 * The hierarchical counterpart of the span ranking: a table says a call was slow,
 * this says whether that call was slow *itself* or merely waiting on something
 * nested inside it — the single most common misreading of a duration. The
 * hierarchy is the span tree, not a sampled call stack: nothing in the capture
 * path profiles the process, so this node draws the nesting that was measured and
 * is named for the shape it draws rather than for a sampling profile.
 */
export const flameNodeSchema = z
  .strictObject({
    type: z.literal('flame'),
    ...queryBackedNodeShape,
  })
  .describe(
    'A hierarchical view of nested timing, drawn as an icicle: each call a bar whose width is its duration and whose children sit beneath it. Suits a question about which call inside a slow operation actually held the time, since a parent wide only because of one child reads differently from a parent wide on its own. Narrow it to a single interaction.',
  );

/** Nested timing drawn as a hierarchy. */
export type FlameNode = z.infer<typeof flameNodeSchema>;

/**
 * A sortable ranking of spans — the "what took longest" table.
 *
 * The most general of the tabular nodes, and the one to reach for when the
 * question is a ranking rather than a grouping: the specialised tables below each
 * add a dimension (render triggers, duplicate counts, statement grouping) that
 * only makes sense for their own concern, while this one shows name, kind, tier
 * and duration for whatever the query selected.
 */
export const tableNodeSchema = z
  .strictObject({
    type: z.literal('table'),
    ...queryBackedNodeShape,
  })
  .describe(
    'A sortable table of spans showing what each one was, which tier produced it and how long it took. Suits a ranking — the slowest operations of a capture, or of one interaction — where a grouped or specialised table would obscure the ordering. Order it by duration and bound the rows to the few that matter; each row that resolved to a source location links to it.',
  );

/** A sortable table of spans. */
export type TableNode = z.infer<typeof tableNodeSchema>;

/**
 * Per-component render counts, timing and trigger attribution.
 *
 * The node a re-render question is built around. A count alone proves nothing —
 * a component that renders often because its inputs changed often is working
 * correctly — so the row carries the attribution too: how many of those renders
 * had stable inputs, how many could not be classified at all, and which inputs
 * changed when they did.
 */
export const renderTableNodeSchema = z
  .strictObject({
    type: z.literal('renderTable'),
    ...queryBackedNodeShape,
  })
  .describe(
    'A table of render statistics per component: how many times each rendered, how much time that took, what triggered those renders, and which of its inputs changed. Suits a question about a component rendering more often than expected, because it separates renders with changed inputs from renders with stable ones and from renders that could not be classified. Order it by count; the component name links to its declaration.',
  );

/** Render statistics per component. */
export type RenderTableNode = z.infer<typeof renderTableNodeSchema>;

/**
 * The component tree with each node's render count.
 *
 * Where the render table gives magnitude, this gives position: a component
 * rendering too often is usually a symptom of where it sits — under which
 * provider, beneath which parent — and that is a shape rather than a number. The
 * tree is the snapshot as it stood at the last commit of the capture, so it is a
 * structure a developer can recognise rather than an average of several.
 */
export const componentTreeNodeSchema = z
  .strictObject({
    type: z.literal('componentTree'),
    ...queryBackedNodeShape,
  })
  .describe(
    'The component hierarchy as it stood at the end of the capture, with each node annotated by how often it rendered, expandable branch by branch. Suits a question where the position of a component explains its behaviour — what it sits beneath and what it provides to. Narrow it to a subtree when the whole tree would bury the answer.',
  );

/** The component hierarchy with per-node render counts. */
export type ComponentTreeNode = z.infer<typeof componentTreeNodeSchema>;

/**
 * Network calls grouped so repeats collide, with duplicate counts.
 *
 * Grouping is the whole point, and it is done on the request as it was actually
 * made rather than on its redacted display form, so byte-identical calls collide
 * and differently parameterized ones stay apart. A group with a count above one
 * is the evidence a duplicate-request question needs, and each occurrence keeps
 * its own initiator so the answer is a place in the code rather than a number.
 */
export const requestTableNodeSchema = z
  .strictObject({
    type: z.literal('requestTable'),
    ...queryBackedNodeShape,
  })
  .describe(
    'A table of network calls grouped so that identical requests collide and differently parameterized ones do not, badged with how many times each group occurred. Suits a question about repeated or redundant calls: expanding a group lists every occurrence with the code that initiated it. Order it by count to bring the repeats to the top.',
  );

/** Network calls grouped for duplicate detection. */
export type RequestTableNode = z.infer<typeof requestTableNodeSchema>;

/**
 * Database statements grouped by parameterized text, with their callers.
 *
 * Statements only. Values are never captured, so a group is the shape of a query
 * and its cost — how often it ran, how long it took — never the data it returned.
 * That is what makes this node safe to show and still useful: a statement
 * repeated once per item of a collection is recognisable from its shape alone.
 */
export const queryTableNodeSchema = z
  .strictObject({
    type: z.literal('queryTable'),
    ...queryBackedNodeShape,
  })
  .describe(
    'A table of database statements grouped by their parameterized text, with how often each ran, how long it took and which code issued it. Statements only: no values and no returned rows are ever captured, so nothing here can expose data. Suits a question where the cost is below the application code — one expensive statement, or one cheap statement run once per item.',
  );

/** Database statements grouped by parameterized text. */
export type QueryTableNode = z.infer<typeof queryTableNodeSchema>;

/**
 * Hook state changes as from-trigger-to rows.
 *
 * The causal chain a render count cannot show: a component rendered because its
 * state changed, and its state changed because something happened. Each row names
 * the component, what its state moved from and to as bounded summaries, and the
 * event that moved it, which is how a re-render panel gets from a symptom to a
 * cause without asserting one.
 */
export const stateTransitionsNodeSchema = z
  .strictObject({
    type: z.literal('stateTransitions'),
    ...queryBackedNodeShape,
  })
  .describe(
    'A table of state changes, one row each: the component, a bounded summary of the value before, the event that triggered the change, and a summary of the value after. Values are summarised and truncated, never captured in full. Suits a question about what is driving a component to update, where the trigger matters more than the count.',
  );

/** State changes as from-trigger-to rows. */
export type StateTransitionsNode = z.infer<typeof stateTransitionsNodeSchema>;

/**
 * The correlated flow as nodes and edges across the tiers.
 *
 * The one structural view: the interaction, the functions it entered, the calls
 * it made and the datastore it ended at, as a layered left-to-right graph built
 * from the correlated trace together with what the code index knows about the
 * project. It answers "what does this interaction touch" — a question no table
 * answers, because the answer is a shape.
 */
export const dependencyGraphNodeSchema = z
  .strictObject({
    type: z.literal('dependencyGraph'),
    ...queryBackedNodeShape,
  })
  .describe(
    'The correlated flow of one interaction as a layered graph: the event, the code it reached, the calls it made and the datastore or external service it ended at, with an edge for each handover. Suits a question about the path an interaction takes rather than the time it spends. Nodes that resolved to a source location link to it.',
  );

/** The correlated flow as a layered graph. */
export type DependencyGraphNode = z.infer<typeof dependencyGraphNodeSchema>;

/*
 * ---------------------------------------------------------------------------
 * The source-link leaf
 * ---------------------------------------------------------------------------
 */

/**
 * A pointer into the developer's own source, rendered as a clickable chip.
 *
 * The one visualization node that carries no query, because its content is not a
 * view of the capture: it is a resolved location, decided before the panel was
 * assembled, by whichever resolution route could vouch for it. Strictness does
 * the rest of the work — every query field is rejected outright, so a specification
 * cannot half-describe this node as a data view.
 *
 * The location is the shared package's single definition rather than a file
 * string with a line number beside it, and that is what makes the chip clickable
 * at all: a click travels from this node through the renderer's action callback,
 * across the extension's port, over the transport's source-open message to the
 * coordination service — which validates the path against the session's project
 * root — and on to the editor, which opens the file and selects the line. Every
 * hop on that path parses the same schema, so a loose string would have to be
 * validated four times and would be trusted at least once.
 *
 * A chip is also embedded by the tables, timelines and graphs above wherever a
 * row resolved to a location; this node is the standalone form, for a panel that
 * wants to point at code directly — beside a hypothesis, or as the conclusion of
 * a section.
 */
export const sourceLinkNodeSchema = z
  .strictObject({
    type: z.literal('sourceLink'),
    ...visualizationNodeShape,

    /**
     * Where in the project this chip points, as the one shared location shape:
     * a project-relative path, a 1-based line and column, an optional symbol,
     * which route resolved it and how much that route trusts the result.
     */
    location: sourceLocationSchema.describe(
      'Where in the project this chip points: a project-relative path with a 1-based line and column, optionally the symbol at that position, plus which resolution route produced it and how much confidence that route has. Must be a location the capture or the code index actually resolved; this node states no query and reads no captured data.',
    ),
  })
  .describe(
    'A standalone link into the project source, rendered as a monospace chip that opens the file at that line in the editor. Suits pointing at the code a finding implicates — beside a hypothesis, or as the conclusion of a section. Carries a resolved location and no query: the tables, timelines and graphs already embed the same chip on any row that resolved to a location.',
  );

/** A standalone pointer into the project source. */
export type SourceLinkNode = z.infer<typeof sourceLinkNodeSchema>;

/*
 * ---------------------------------------------------------------------------
 * Unions and the schema tuple
 *
 * What the specification module consumes. It imports the tuple below, spreads it
 * beside the layout factories and closes the recursion in one discriminated
 * union — which is precisely what stops it from hand-listing thirteen imports
 * and silently omitting one.
 * ---------------------------------------------------------------------------
 */

/**
 * Any node whose content is a prepared view of the capture.
 *
 * The twelve members carry a data query and are resolved through the
 * renderer's data provider; the source-link leaf is deliberately not one of them.
 * This is the type to accept wherever the operation is "resolve this node's data"
 * rather than "render this node".
 */
export type QueryBackedNode =
  | TimelineNode
  | WaterfallNode
  | EventLogNode
  | MetricCardsNode
  | FlameNode
  | TableNode
  | RenderTableNode
  | ComponentTreeNode
  | RequestTableNode
  | QueryTableNode
  | StateTransitionsNode
  | DependencyGraphNode;

/**
 * Any node that draws something: the twelve query-backed nodes plus the
 * source-link leaf.
 *
 * Discriminated by `type`, so narrowing it is a `switch` the compiler can check
 * exhaustively — which is how the renderer's node dispatch and the validator's
 * per-type checks stay complete as the vocabulary grows. The panel node union
 * itself is the specification module's: it is this union plus the layout nodes,
 * and only that module can state it without closing the recursion twice.
 */
export type VisualizationNode = QueryBackedNode | SourceLinkNode;

/**
 * A schema that parses an object whose `type` is the given literal, described
 * structurally.
 *
 * Structural rather than `z.ZodType<{ type: T }>` on purpose: a schema is
 * effectively invariant in what it parses, because its own refinement callbacks
 * put that type in both an argument and a return position, so the schema-typed
 * target would reject a concrete node schema for having *more* fields than the
 * target names. Matching on the internals' parsed-output type instead is
 * covariant, which is what lets a full node schema satisfy "parses something
 * whose `type` is this literal" while still failing when the literal is wrong.
 */
type SchemaParsingNodeType<T extends string> = {
  readonly _zod: { readonly output: { readonly type: T } };
};

/**
 * Compile-time proof that {@link VISUALIZATION_NODE_SCHEMAS} lists exactly one
 * schema per member of {@link VISUALIZATION_NODE_TYPES}, in the same order.
 *
 * A homomorphic mapped type over the type vocabulary, so it *is* a tuple of the
 * same length, and each position demands a schema parsing the literal at that
 * position. Written as a generic over `T` rather than directly over the frozen
 * vocabulary because only the generic form maps element positions alone: applied
 * to a concrete frozen tuple, the mapping would also map `length` and the array
 * methods and could never be satisfied.
 *
 * What it catches, in this file, at compile time: a schema omitted, a schema
 * listed twice, the tuple and the type vocabulary drifting out of order, and a
 * new node type added to the vocabulary without a schema beside it. Used only in
 * the `satisfies` clause below, so it constrains without widening: the exported
 * constant keeps its precise tuple type and the specification module still gets
 * each option's own schema type when it spreads it.
 */
type NodeSchemaTupleFor<T extends readonly string[]> = {
  readonly [K in keyof T]: SchemaParsingNodeType<T[K]>;
};

/**
 * Every visualization node schema, in {@link VISUALIZATION_NODE_TYPES} order.
 *
 * This is the module's primary export for the specification module, which
 * spreads it into the panel node union beside the layout nodes. Exporting the
 * tuple rather than leaving the consumer to import thirteen names is what makes
 * the union provably complete: a node type added below without an entry here
 * fails the `satisfies` clause in this file, and an entry here with no catalog
 * entry fails the catalog's test — so the vocabulary, the schemas, the catalog
 * and, downstream, the renderer's component registry cannot drift apart
 * silently.
 *
 * Frozen, like every other vocabulary in this folder: it is shared, read-only
 * and built once at module load with no side effect.
 */
export const VISUALIZATION_NODE_SCHEMAS = Object.freeze([
  timelineNodeSchema,
  waterfallNodeSchema,
  eventLogNodeSchema,
  metricCardsNodeSchema,
  flameNodeSchema,
  tableNodeSchema,
  renderTableNodeSchema,
  componentTreeNodeSchema,
  requestTableNodeSchema,
  queryTableNodeSchema,
  stateTransitionsNodeSchema,
  dependencyGraphNodeSchema,
  sourceLinkNodeSchema,
] as const) satisfies NodeSchemaTupleFor<typeof VISUALIZATION_NODE_TYPES>;
