// @vitest-environment happy-dom
/**
 * "Pick element" through the real page agent: a relayed `target.request`
 * arms `./dom-target.ts`'s interactive picker, and the one `target.described`
 * answer reaches the bridge only when that pick ends.
 *
 * **What this suite owns.** The wire contract between the service worker and
 * the page agent, read where the real bridge reads it — the agent's private
 * channel node, through the fake bridge in `./__tests__/page-channel.ts`:
 *
 * - `target.request { requestId?, cancel? }` — without `cancel`, arm one pick
 *   and post nothing yet; a newer request supersedes the pick in flight; a
 *   request while element description is released is answered at once; with
 *   `cancel: true`, end the pick in flight, or post nothing when there is none.
 * - `target.described { target, requestId? }` — exactly one answer per armed
 *   pick: the five-field descriptor for a trusted primary click, `null` for
 *   Escape, a cancel request, a superseding request, `bridge.gone` and
 *   `pagehide`, always under the request's own `requestId`, and without the
 *   key when the request carried none.
 * - `bridge.gone` — ends the pick in flight and nothing else, so a pick never
 *   outlives the relay that armed it: the developer's next click is the
 *   page's, and the bridge's `bridge.ready` afterwards re-arms nothing. A
 *   `bridge.ready` that finds a pick still armed — a port loss the bridge did
 *   not report — ends it the same way.
 *
 * The picker's mechanics — which events are consumed, the trusted-only rule,
 * the overlay, teardown and residue — are `./dom-target.test.ts`'s; this file
 * proves the agent drives them and answers for them.
 *
 * **Harness.** Importing `./agent.js` runs its opening sequence, which arms
 * the document-scoped `domTarget` family and subscribes to the bridge; the fake
 * bridge is connected once at module scope because the transport answers
 * exactly one handshake per document. Every case clears the recorded frames,
 * and teardown cancels any pick left in flight and dispatches `pageshow` —
 * the agent's own re-arm path — so a case that released the family hands the
 * next one an armed document. happy-dom constructs events without an
 * `isTrusted` property; a browser-generated gesture is modelled by defining it
 * `true` on the event before dispatch, which is the one field the picker reads
 * to tell a gesture from a page script.
 */
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { connectFakeBridge } from './__tests__/page-channel.js';
import type { FakeBridge } from './__tests__/page-channel.js';
import { getAgentState } from './agent.js';
import { hasElementPickResidue, isElementPickActive } from './dom-target.js';
import { AGENT_SOURCE_TAG, getTransportStats, subscribe } from './transport.js';

/** The fake bridge, holding the agent's channel node for the whole file. */
const bridge: FakeBridge = connectFakeBridge({ subscribe });

/** The `target.described` payloads the agent dispatched in this case, in order. */
function answers(): Readonly<Record<string, unknown>>[] {
  return bridge
    .framesOfType('target.described')
    .filter((frame) => frame.source === AGENT_SOURCE_TAG)
    .map((frame) => frame.payload);
}

/** Mark an event as generated by the browser rather than by a page script. */
function asTrusted<T extends Event>(event: T): T {
  Object.defineProperty(event, 'isTrusted', { value: true });
  return event;
}

/** A trusted, bubbling, cancelable primary-button click. */
function trustedClick(): MouseEvent {
  return asTrusted(
    new MouseEvent('click', { bubbles: true, cancelable: true, composed: true, button: 0 }),
  );
}

/** `<button id="apply-filter">Apply</button>`, in the document. */
function mountButton(): HTMLButtonElement {
  const button = document.createElement('button');
  button.id = 'apply-filter';
  button.textContent = 'Apply';
  document.body.appendChild(button);
  return button;
}

/** Send one `target.request` and require the agent to have taken it. */
function request(payload: Record<string, unknown>): void {
  expect(bridge.send('target.request', payload)).toBe(true);
}

beforeEach(() => {
  bridge.clear();
  expect(getAgentState().hooks['domTarget']).toBe(true);
});

afterEach(() => {
  request({ cancel: true });
  window.dispatchEvent(new Event('pageshow'));
  bridge.clear();
  document.body.replaceChildren();
});

describe('target.request arms an interactive pick', () => {
  it('posts no answer until the developer picks', () => {
    request({ requestId: 'r1' });

    expect(answers()).toEqual([]);
    expect(isElementPickActive()).toBe(true);
  });

  it('answers a trusted click with the five-field descriptor under the request id, exactly once', () => {
    const button = mountButton();
    let pageSawClick = false;
    button.addEventListener('click', () => {
      pageSawClick = true;
    });
    request({ requestId: 'r1' });

    const click = trustedClick();
    button.dispatchEvent(click);

    expect(answers()).toEqual([
      {
        target: {
          selector: '#apply-filter',
          tagName: 'button',
          text: 'Apply',
          componentChain: [],
          url: window.location.href,
        },
        requestId: 'r1',
      },
    ]);
    // The picking click was the picker's: the page never ran its handler.
    expect(click.defaultPrevented).toBe(true);
    expect(pageSawClick).toBe(false);
    expect(isElementPickActive()).toBe(false);
    expect(hasElementPickResidue()).toBe(false);

    // The pick has ended: the next click is the page's and answers nothing.
    button.dispatchEvent(trustedClick());
    expect(pageSawClick).toBe(true);
    expect(answers()).toHaveLength(1);
  });

  it('ignores a click a page script dispatched', () => {
    const button = mountButton();
    request({ requestId: 'r1' });

    button.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true, button: 0 }));

    expect(answers()).toEqual([]);
    expect(isElementPickActive()).toBe(true);
  });

  it('omits requestId from the answer when the request carried none', () => {
    const button = mountButton();
    request({});

    button.dispatchEvent(trustedClick());

    const [answer] = answers();
    expect(answers()).toHaveLength(1);
    expect(answer?.['target']).toMatchObject({ selector: '#apply-filter' });
    expect(answer !== undefined && 'requestId' in answer).toBe(false);
  });
});

describe('every armed pick is answered exactly once', () => {
  it('answers null under the request id when the panel cancels, and nothing on a second cancel', () => {
    request({ requestId: 'r1' });

    request({ cancel: true });
    expect(answers()).toEqual([{ target: null, requestId: 'r1' }]);
    expect(isElementPickActive()).toBe(false);

    request({ cancel: true });
    expect(answers()).toHaveLength(1);
  });

  it('posts nothing for a cancel when no pick is in flight', () => {
    request({ cancel: true, requestId: 'r9' });

    expect(answers()).toEqual([]);
  });

  it('answers null when the developer presses Escape on the page', () => {
    request({ requestId: 'r1' });

    const escape = asTrusted(
      new KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true }),
    );
    document.body.dispatchEvent(escape);

    expect(answers()).toEqual([{ target: null, requestId: 'r1' }]);
    expect(escape.defaultPrevented).toBe(true);
    expect(isElementPickActive()).toBe(false);
  });

  it('answers the superseded request with null before the newer one is picked', () => {
    const button = mountButton();
    request({ requestId: 'r1' });

    request({ requestId: 'r2' });
    expect(answers()).toEqual([{ target: null, requestId: 'r1' }]);
    expect(isElementPickActive()).toBe(true);

    button.dispatchEvent(trustedClick());
    const all = answers();
    expect(all).toHaveLength(2);
    expect(all[1]).toMatchObject({ target: { selector: '#apply-filter' }, requestId: 'r2' });
  });

  it('answers null when the document goes away, from inside pagehide', () => {
    request({ requestId: 'r1' });

    window.dispatchEvent(new Event('pagehide'));

    expect(answers()).toEqual([{ target: null, requestId: 'r1' }]);
    expect(isElementPickActive()).toBe(false);
    expect(getAgentState().hooks['domTarget']).toBe(false);
  });

  it('answers null at once while element description is released, and arms again after pageshow', () => {
    window.dispatchEvent(new Event('pagehide'));
    bridge.clear();

    request({ requestId: 'r3' });
    expect(answers()).toEqual([{ target: null, requestId: 'r3' }]);
    expect(isElementPickActive()).toBe(false);

    window.dispatchEvent(new Event('pageshow'));
    bridge.clear();
    request({ requestId: 'r4' });
    expect(answers()).toEqual([]);
    expect(isElementPickActive()).toBe(true);
  });
});

describe('a pick never outlives the relay that armed it', () => {
  afterEach(() => {
    // A case here may leave the bridge reported gone; the bridge's reconnect
    // is restored so the next case starts with the bridge present.
    bridge.send('bridge.ready');
  });

  it('answers null under the request id on bridge.gone, ending only the pick', () => {
    request({ requestId: 'r1' });

    expect(bridge.send('bridge.gone')).toBe(true);

    expect(answers()).toEqual([{ target: null, requestId: 'r1' }]);
    expect(isElementPickActive()).toBe(false);
    expect(hasElementPickResidue()).toBe(false);
    // Everything else `bridge.gone` does is unchanged: the transport buffers
    // while the bridge is away, and element description stays attached.
    expect(getTransportStats().bridgeReady).toBe(false);
    expect(getAgentState().hooks['domTarget']).toBe(true);
  });

  it("hands the developer's next click back to the page, and bridge.ready re-arms nothing", () => {
    const button = mountButton();
    let pageClicks = 0;
    button.addEventListener('click', () => {
      pageClicks += 1;
    });
    request({ requestId: 'r1' });
    bridge.send('bridge.gone');

    const afterGone = trustedClick();
    button.dispatchEvent(afterGone);
    expect(afterGone.defaultPrevented).toBe(false);
    expect(pageClicks).toBe(1);

    // The bridge reconnects to the same document. Nothing re-arms: the click
    // after it is the page's too, and no further answer is posted.
    expect(bridge.send('bridge.ready')).toBe(true);
    expect(isElementPickActive()).toBe(false);
    const afterReady = trustedClick();
    button.dispatchEvent(afterReady);
    expect(afterReady.defaultPrevented).toBe(false);
    expect(pageClicks).toBe(2);
    expect(answers()).toEqual([{ target: null, requestId: 'r1' }]);

    // A request the reconnected worker sends arms a fresh pick as usual.
    request({ requestId: 'r2' });
    const picking = trustedClick();
    button.dispatchEvent(picking);
    expect(picking.defaultPrevented).toBe(true);
    expect(pageClicks).toBe(2);
    const all = answers();
    expect(all).toHaveLength(2);
    expect(all[1]).toMatchObject({ target: { selector: '#apply-filter' }, requestId: 'r2' });
  });

  it('posts the answer once, unclaimed and counted, when the bridge has no port to relay it', () => {
    // The real bridge reports `bridge.gone` after its port closed, so it has
    // nowhere to put the answer and leaves it unclaimed.
    bridge.claim = (frame) => frame.type !== 'target.described';
    const droppedBefore = getTransportStats().controlFramesDropped;
    request({ requestId: 'r1' });

    bridge.send('bridge.gone');

    const described = bridge.framesOfType('target.described');
    expect(described.map((frame) => [frame.payload, frame.claimed])).toEqual([
      [{ target: null, requestId: 'r1' }, false],
    ]);
    expect(getTransportStats().controlFramesDropped).toBe(droppedBefore + 1);
    expect(isElementPickActive()).toBe(false);

    // A control frame is never queued: the reconnect does not resend it.
    bridge.send('bridge.ready');
    expect(bridge.framesOfType('target.described')).toHaveLength(1);
  });

  it('posts nothing on bridge.gone when no pick is in flight', () => {
    expect(bridge.send('bridge.gone')).toBe(true);

    expect(answers()).toEqual([]);
    expect(isElementPickActive()).toBe(false);
  });

  it('ends a pick an unreported port loss left armed, on the next bridge.ready', () => {
    // A port that fails inside the agent's own frame dispatch is lost without
    // a `bridge.gone`; the bridge's next port announces itself with
    // `bridge.ready` only, and the pick armed through the old one must end.
    const button = mountButton();
    let pageClicks = 0;
    button.addEventListener('click', () => {
      pageClicks += 1;
    });
    request({ requestId: 'r1' });

    expect(bridge.send('bridge.ready')).toBe(true);

    expect(answers()).toEqual([{ target: null, requestId: 'r1' }]);
    expect(isElementPickActive()).toBe(false);
    const click = trustedClick();
    button.dispatchEvent(click);
    expect(click.defaultPrevented).toBe(false);
    expect(pageClicks).toBe(1);
    expect(getAgentState().hooks['domTarget']).toBe(true);
  });

  it('posts nothing on bridge.ready when no pick is in flight', () => {
    expect(bridge.send('bridge.ready')).toBe(true);

    expect(answers()).toEqual([]);
    expect(isElementPickActive()).toBe(false);
  });
});
