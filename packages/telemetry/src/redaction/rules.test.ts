/**
 * The inclusive character range from `first` to `last`, by code unit.
 *
 * Used instead of writing an alphabet out: a 64-character alphabet literal is
 * both long and high-entropy, which is precisely the shape the secret gate's
 * `entropy` rule looks for.
 */
function charRange(first: string, last: string): string {
  let result = '';
  for (let code = first.charCodeAt(0); code <= last.charCodeAt(0); code += 1) {
    result += String.fromCharCode(code);
  }
  return result;
}

const DIGITS = charRange('0', '9');
const LOWER_LETTERS = charRange('a', 'z');
const UPPER_LETTERS = charRange('A', 'Z');

/** Lower-case hexadecimal: exactly 16 symbols, so at most 4 bits per character. */
const HEX_CHARS = DIGITS + charRange('a', 'f');

/** Base64url alphabet: 64 symbols, so 6 bits per character when cycled. */
const URLSAFE_CHARS = UPPER_LETTERS + LOWER_LETTERS + DIGITS + '-_';

/** Body characters of underscore-delimited forge tokens. */
const WORD_CHARS = UPPER_LETTERS + LOWER_LETTERS + DIGITS + '_';

/** Body characters of upper-case cloud access identifiers. */
const UPPER_ID_CHARS = UPPER_LETTERS + DIGITS;

/** Credential characters permitted after an HTTP authentication scheme. */
const BEARER_CHARS = UPPER_LETTERS + LOWER_LETTERS + DIGITS + '._~+/=-';

/**
 * A deterministic body of `length` characters cycled from `alphabet`.
 *
 * Deterministic rather than random so a failure is reproducible, and cycled
 * over the whole alphabet so the result is dense enough to look like key
 * material to the module under test.
 */
function cycle(alphabet: string, length: number): string {
  let result = '';
  for (let index = 0; index < length; index += 1) {
    result += alphabet.charAt(index % alphabet.length);
  }
  return result;
}

/**
 * A value of `length` characters drawn evenly from the first `symbolCount`
 * symbols of the base64url alphabet.
 *
 * When `length` is a multiple of `symbolCount` every symbol appears the same
 * number of times, so the value's Shannon entropy is exactly
 * `log2(symbolCount)` bits per character. That is what lets the entropy cases
 * below sit at a stated distance from the module's threshold — 17 symbols for
 * 4.0875 bits, 16 for exactly 4, 15 for 3.9069 — instead of merely somewhere
 * above or below it.
 */
function evenDistribution(symbolCount: number, length: number): string {
  return cycle(URLSAFE_CHARS.slice(0, symbolCount), length);
}

/**
 * Joins credential fragments.
 *
 * Every call site exists to keep a credential prefix from appearing as one
 * contiguous literal in this tracked file. The split points carry no meaning
 * beyond that, which is worth knowing before "simplifying" a call away.
 */
function assemble(...fragments: readonly string[]): string {
  return fragments.join('');
}

