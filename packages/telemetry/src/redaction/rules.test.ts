/**
 * Names that denote a value which must never be captured, in the spellings
 * the wire actually carries: HTTP header casings, snake_case and camelCase
 * attribute keys, and the dotted OpenTelemetry header convention.
 */
const SENSITIVE_NAMES: readonly string[] = [
  'authorization',
  'Authorization',
  'x-api-key',
  'X-Api-Key',
  'api_key',
  'apiKey',
  'token',
  'accessToken',
  'secret',
  'password',
  'pwd',
  'credential',
  'http.request.header.authorization',
];

/**
 * Names that must survive the vocabulary.
 *
 * The first four are the product's own correlation identifiers - a session
 * that redacted its own `sessionId` would break every panel - and the last two
 * are ordinary evidence the analysis pipeline reads.
 */
const NON_SENSITIVE_NAMES: readonly string[] = [
  'sessionId',
  'request_key',
  'traceId',
  'spanId',
  'component',
  'db.statement',
];

describe('isSensitiveKeyName', () => {
  for (const name of SENSITIVE_NAMES) {
    it('treats ' + name + ' as sensitive', () => {
      expect(isSensitiveKeyName(name)).toBe(true);
    });
  }

  for (const name of NON_SENSITIVE_NAMES) {
    it('leaves ' + name + ' alone', () => {
      // Deliberate exclusions, not oversights: `session` is absent from the
      // vocabulary so `sessionId` survives, and `request_key` is exempted by
      // exact name so the duplicate-request grouping key reaches the panel.
      expect(isSensitiveKeyName(name)).toBe(false);
    });
  }

  it('matches regardless of separator spelling or case', () => {
    for (const spelling of ['apikey', 'API-KEY', 'api key', 'api.key', 'Api_Key']) {
      expect(isSensitiveKeyName(spelling)).toBe(true);
    }
  });

  it('still treats a decorated variant of an exempt name as sensitive', () => {
    // The exemptions match the whole normalised name, so a header that merely
    // contains one of them is not waved through.
    expect(isSensitiveKeyName('x-request-key')).toBe(true);
  });

  it('reports an empty name as not sensitive', () => {
    expect(isSensitiveKeyName('')).toBe(false);
    expect(isSensitiveKeyName('   ')).toBe(false);
  });
});

describe('scrubNamedValue', () => {
  it('replaces a short low-entropy value under a sensitive name', () => {
    // Redaction is stricter than detection on purpose: a four-character
    // password is still a password, so the name alone decides.
    expect(scrubNamedValue('password', 'short')).toBe(REDACTION_MARKER);
  });

  it('leaves a value under an ordinary name untouched', () => {
    // A deliberately neutral component name: the anti-hardcoding gate forbids
    // any identifier of the demo application from appearing in package source.
    expect(scrubNamedValue('component', 'SampleWidget')).toBe('SampleWidget');
  });

  it('still scrubs by content when the name is not sensitive', () => {
    expect(scrubNamedValue('component', 'rendered with ' + GENERIC_KEY)).toBe(
      'rendered with ' + REDACTION_MARKER,
    );
  });

  it('returns an empty value as is, even under a sensitive name', () => {
    expect(scrubNamedValue('authorization', '')).toBe('');
  });

  it('replaces every value under a sensitive name whatever its shape', () => {
    for (const name of SENSITIVE_NAMES) {
      expect(scrubNamedValue(name, 'a')).toBe(REDACTION_MARKER);
      expect(scrubNamedValue(name, cycle(LOWER_LETTERS, 40))).toBe(REDACTION_MARKER);
    }
  });
});

describe('shannonEntropy', () => {
  it('is zero for an empty string', () => {
    expect(shannonEntropy('')).toBe(0);
  });

  it('is zero for a single repeated character', () => {
    expect(shannonEntropy('a')).toBe(0);
    expect(shannonEntropy('a'.repeat(64))).toBe(0);
  });

  it('reaches log2(n) for n evenly distributed symbols', () => {
    // 16 hexadecimal symbols cycled evenly measure exactly 4 bits per
    // character, and a 64-symbol base64url alphabet exactly 6.
    expect(shannonEntropy(cycle(HEX_CHARS, 64))).toBeCloseTo(4, 10);
    expect(shannonEntropy(cycle(URLSAFE_CHARS, 64))).toBeCloseTo(6, 10);
  });

  it('places a dense alphabet above the threshold and a sparse one below it', () => {
    // The assertion is the comparison against the module's own bar, never a
    // magic number: hexadecimal sits exactly on 4 bits per character, so the
    // fixtures are chosen to fall clearly on either side of it.
    expect(shannonEntropy(cycle(URLSAFE_CHARS, 64))).toBeGreaterThan(ENTROPY_MIN_BITS_PER_CHAR);
    expect(shannonEntropy(cycle('abcd', 64))).toBeLessThan(ENTROPY_MIN_BITS_PER_CHAR);
  });

  it('is always finite and non-negative, including for astral characters', () => {
    for (const value of ['', 'a', 'ab', '\u{1F600}\u{1F601}', cycle(URLSAFE_CHARS, 200)]) {
      const bits = shannonEntropy(value);

      expect(Number.isFinite(bits)).toBe(true);
      expect(bits).toBeGreaterThanOrEqual(0);
    }
  });
});

describe('isHighEntropySecret', () => {
  it('accepts a value that is long enough and dense enough', () => {
    const dense = cycle(URLSAFE_CHARS, ENTROPY_MIN_LENGTH);

    expect(dense).toHaveLength(ENTROPY_MIN_LENGTH);
    expect(shannonEntropy(dense)).toBeGreaterThan(ENTROPY_MIN_BITS_PER_CHAR);
    expect(isHighEntropySecret(dense)).toBe(true);
  });

  it('rejects a dense value one character short of the minimum length', () => {
    const tooShort = cycle(URLSAFE_CHARS, ENTROPY_MIN_LENGTH - 1);

    expect(shannonEntropy(tooShort)).toBeGreaterThan(ENTROPY_MIN_BITS_PER_CHAR);
    expect(isHighEntropySecret(tooShort)).toBe(false);
  });

  it('rejects a long value that is not dense enough', () => {
    const sparse = cycle('abcd', ENTROPY_MIN_LENGTH * 2);

    expect(shannonEntropy(sparse)).toBeLessThan(ENTROPY_MIN_BITS_PER_CHAR);
    expect(isHighEntropySecret(sparse)).toBe(false);
  });

  it('requires entropy strictly above the bar, not merely equal to it', () => {
    // A balanced hexadecimal digest measures exactly the threshold. Digests are
    // evidence rather than credentials, so sitting on the bar is not enough.
    const digest = cycle(HEX_CHARS, 64);

    expect(shannonEntropy(digest)).toBeCloseTo(ENTROPY_MIN_BITS_PER_CHAR, 10);
    expect(isHighEntropySecret(digest)).toBe(false);
  });

  it('rejects an empty value', () => {
    expect(isHighEntropySecret('')).toBe(false);
  });
});

