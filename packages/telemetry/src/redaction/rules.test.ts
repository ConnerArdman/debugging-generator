describe('scrub', () => {
  describe('provider credentials', () => {
    for (const { label, value } of PROVIDER_CREDENTIALS) {
      it('replaces ' + label + ' and keeps the surrounding text', () => {
        const scrubbed = scrub('header carried ' + value + ' verbatim');

        expect(scrubbed).toBe('header carried ' + REDACTION_MARKER + ' verbatim');
        expect(scrubbed).not.toContain(value);
        expect(scrubbed).toContain(REDACTION_MARKER);
      });

      it('leaves no tail of ' + label + ' behind when it is longer than its usual shape', () => {
        // The pattern identifies a credential on a bounded prefix and then
        // consumes the rest of the run; without that second quantifier a long
        // credential would be replaced only up to the identifying length and
        // the remainder would survive.
        const overlong = value + cycle(DIGITS, 200);

        expect(scrub(overlong)).toBe(REDACTION_MARKER);
      });
    }
  });

  describe('bearer credentials', () => {
    it('keeps the scheme word and replaces only the credential', () => {
      expect(scrub('authorization: ' + BEARER_HEADER_VALUE)).toBe(
        'authorization: ' + BEARER_SCHEME + ' ' + REDACTION_MARKER,
      );
    });

    it('preserves the scheme exactly as written, whatever its case', () => {
      // Presence is diagnostic - that a request was authenticated explains a
      // 401 or a cache miss - so the scheme survives; only the credential goes.
      expect(scrub('bearer ' + BEARER_CREDENTIAL)).toBe('bearer ' + REDACTION_MARKER);
      expect(scrub('BEARER ' + BEARER_CREDENTIAL)).toBe('BEARER ' + REDACTION_MARKER);
    });

    it('never returns any part of the credential', () => {
      const scrubbed = scrub(BEARER_HEADER_VALUE);

      expect(scrubbed).not.toContain(BEARER_CREDENTIAL);
      expect(scrubbed).not.toContain(BEARER_CREDENTIAL.slice(0, 12));
    });
  });

  describe('JOSE tokens', () => {
    it('replaces a signed three-segment token', () => {
      expect(scrub('cookie: session=' + JWT_SIGNED + ';')).toBe(
        'cookie: session=' + REDACTION_MARKER + ';',
      );
    });

    it('replaces an unsigned token whose third segment is empty', () => {
      expect(scrub('value ' + JWT_UNSIGNED)).toBe('value ' + REDACTION_MARKER);
    });

    it('replaces a token that has only a header and a payload', () => {
      // A token cut short by the scan window, or an unsigned token serialised
      // without the trailing separator, must not pass through with its claims
      // readable.
      expect(scrub('value ' + JWT_TWO_SEGMENT)).toBe('value ' + REDACTION_MARKER);
    });
  });

  describe('PEM private keys', () => {
    it('replaces a complete block precisely, keeping the text around it', () => {
      expect(scrub('before\n' + PEM_BLOCK + '\nafter')).toBe(
        'before\n' + REDACTION_MARKER + '\nafter',
      );
    });

    it('replaces a header and everything after it when no footer arrived', () => {
      // Bounded fallback: the remainder of a value that begins a private-key
      // block is key material by construction, so it goes with the header.
      const scrubbed = scrub('before\n' + PEM_OPEN_BLOCK);

      expect(scrubbed).toBe('before\n' + REDACTION_MARKER);
      expect(scrubbed).not.toContain(PEM_TAIL);
    });
  });

  describe('credentialed connection strings', () => {
    it('replaces the userinfo and keeps the scheme, host, port and database', () => {
      const scrubbed = scrub('DATABASE_URL=' + CONNECTION_STRING);

      expect(scrubbed).toBe(
        'DATABASE_URL=' + CONNECTION_SCHEME + REDACTION_MARKER + '@' + CONNECTION_AUTHORITY,
      );
      expect(scrubbed).toContain(CONNECTION_AUTHORITY);
      expect(scrubbed).not.toContain('demo_user');
    });

    it('leaves a URL that carries no credentials alone', () => {
      // `host:port` followed by an `@` inside a path must not be mistaken for
      // userinfo, and a plain authority has nothing to redact.
      const plain = 'http://127.0.0.1:3000/v1/items';

      expect(scrub(plain)).toBe(plain);
    });
  });

  describe('multiple and embedded credentials', () => {
    it('replaces a credential embedded mid-sentence without touching the prose', () => {
      expect(
        scrub('The request failed because the header carried ' + GENERIC_KEY + ' in plain text.'),
      ).toBe(
        'The request failed because the header carried ' + REDACTION_MARKER + ' in plain text.',
      );
    });

    it('replaces every credential in a value that carries two', () => {
      const scrubbed = scrub('first ' + GENERIC_KEY + ' then ' + ACCESS_KEY_ID + ' done');

      expect(scrubbed).toBe('first ' + REDACTION_MARKER + ' then ' + REDACTION_MARKER + ' done');
      expect(scrubbed).not.toContain(GENERIC_KEY);
      expect(scrubbed).not.toContain(ACCESS_KEY_ID);
    });

    it('replaces credentials of two different classes in one value', () => {
      const scrubbed = scrub(JWT_SIGNED + ' / ' + BEARER_HEADER_VALUE);

      expect(scrubbed).toBe(REDACTION_MARKER + ' / ' + BEARER_SCHEME + ' ' + REDACTION_MARKER);
    });
  });

  describe('values with nothing to hide', () => {
    for (const { label, value } of CLEAN_FIXTURES) {
      it('returns ' + label + ' unchanged', () => {
        // Over-redaction is not free: these are the values the panel is built
        // from, so each has to survive byte-for-byte.
        expect(scrub(value)).toBe(value);
      });
    }
  });
});

