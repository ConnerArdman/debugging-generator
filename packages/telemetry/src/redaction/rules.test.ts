/** Every fixture of the suite, secrets and clean values alike. */
const ALL_FIXTURES: readonly Fixture[] = [...SECRET_FIXTURES, ...CLEAN_FIXTURES];

/** Wall-clock milliseconds spent in `work`. */
function elapsedMs(work: () => void): number {
  const started = performance.now();
  work();
  return performance.now() - started;
}

/**
 * Generous ceiling for the adversarial inputs below.
 *
 * The measured cost of each of them is a few milliseconds, so a full second
 * fails only on genuinely exponential backtracking and never because a CI
 * runner was busy.
 */
const ADVERSARIAL_BUDGET_MS = 1_000;

/** Deterministic hostile text: dense, punctuated and never the same twice over. */
function pseudoRandomText(length: number, seedValue: number): string {
  const alphabet = UPPER_LETTERS + LOWER_LETTERS + DIGITS + ' .:/?#@-_=+~';
  const chunks: string[] = [];
  let seed = seedValue;
  for (let index = 0; index < length; index += 1) {
    seed = (seed * 1103515245 + 12345) % 2147483648;
    chunks.push(alphabet.charAt(seed % alphabet.length));
  }
  return chunks.join('');
}

describe('properties', () => {
  it('scrubs idempotently', () => {
    // Two rules grow the text they replace, so a second pass over a scrubbed
    // value is exactly where a pattern that matches its own output would show
    // up. The traps - the marker and the `Bearer [redacted]` form - are part of
    // the fixture set.
    for (const { label, value } of ALL_FIXTURES) {
      const once = scrub(value);

      expect(scrub(once), label).toBe(once);
      expect(scrub(scrub(once)), label).toBe(once);
    }
  });

  it('truncates idempotently at every bound a caller uses', () => {
    for (const { label, value } of ALL_FIXTURES) {
      for (const bound of [CALLER_PREVIEW_LENGTH, 10, 1]) {
        const once = truncate(value, bound);

        expect(truncate(once, bound), label + ' at ' + bound).toBe(once);
      }
    }
  });

  it('truncates a value already at the bound to itself', () => {
    const exact = cycle(LOWER_LETTERS, CALLER_PREVIEW_LENGTH);

    expect(codePoints(exact)).toHaveLength(CALLER_PREVIEW_LENGTH);
    expect(truncate(exact, CALLER_PREVIEW_LENGTH)).toBe(exact);
  });

  it('never returns unscanned input beyond the scan bound', () => {
    const planted = 'x'.repeat(MAX_SCAN_LENGTH) + ' ' + GENERIC_KEY;
    const scrubbed = scrub(planted);

    expect(scrubbed.length).toBeLessThanOrEqual(MAX_SCAN_LENGTH);
    expect(scrubbed.endsWith(REDACTION_MARKER)).toBe(true);
    // The credential sits past the bound, so it was never examined - and
    // therefore must not have been returned either.
    expect(scrubbed).not.toContain(GENERIC_KEY);
    expect(scrubbed).not.toContain(GENERIC_KEY.slice(0, 16));
    expect(scrub(scrubbed)).toBe(scrubbed);
  });

  it('keeps its output within the scan bound even when a rule grows the text', () => {
    // A scheme word plus an eight-character credential (15 characters) comes
    // back as the scheme plus the marker (17 characters), so a value just under
    // the bound comes back over it unless the result is clamped - and an
    // unclamped result would also break idempotence, because the next call
    // would take the bounded path and append a second marker.
    const occurrence = BEARER_SCHEME + ' ' + cycle(LOWER_LETTERS, 8) + ' ';
    const occurrences = Math.floor((MAX_SCAN_LENGTH - 1) / occurrence.length);
    const nearBound = occurrence.repeat(occurrences);
    const redactedLength = (BEARER_SCHEME + ' ' + REDACTION_MARKER + ' ').length;
    const scrubbed = scrub(nearBound);

    expect(nearBound.length).toBeLessThanOrEqual(MAX_SCAN_LENGTH);
    expect(occurrences * redactedLength).toBeGreaterThan(MAX_SCAN_LENGTH);
    expect(scrubbed.length).toBeLessThanOrEqual(MAX_SCAN_LENGTH);
    expect(scrubbed.endsWith(REDACTION_MARKER)).toBe(true);
    expect(scrubbed).not.toContain(cycle(LOWER_LETTERS, 8));
    expect(scrub(scrubbed)).toBe(scrubbed);
  });

  it('leaves a value of exactly the scan bound to the unbounded path', () => {
    const exact = 'z'.repeat(MAX_SCAN_LENGTH);

    expect(scrub(exact)).toBe(exact);
  });

  it('never cuts a surrogate pair when it truncates at the scan bound', () => {
    // The astral characters start at an odd code-unit offset, so the bound falls
    // between the two halves of one of them. A blind slice would emit a lone
    // surrogate - an unpaired code unit that breaks JSON transport and renders
    // as a replacement character in the panel.
    const astralOverflow = 'a' + '\u{1F600}'.repeat(MAX_SCAN_LENGTH);
    const scrubbed = scrub(astralOverflow);

    expect(astralOverflow.length).toBeGreaterThan(MAX_SCAN_LENGTH);
    expect(scrubbed.length).toBeLessThanOrEqual(MAX_SCAN_LENGTH);
    expect(scrubbed.endsWith(REDACTION_MARKER)).toBe(true);
    expect(hasLoneSurrogate(scrubbed)).toBe(false);
    expect(scrub(scrubbed)).toBe(scrubbed);
  });

  it('resists catastrophic backtracking on hostile input', () => {
    const noise = pseudoRandomText(200_000, 12_345);
    const openedPem = PEM_HEADER.slice(0, PEM_HEADER.length - 8) + 'A'.repeat(50_000);
    const repeatedHeader = (PEM_DASHES + 'BEGIN ').repeat(2_000);
    const longBearer = BEARER_SCHEME + ' ' + cycle(BEARER_CHARS, 10_000);
    const hostile: readonly Fixture[] = [
      { label: '200 KB of dense punctuated text', value: noise },
      { label: 'a truncated key header before a long single-character run', value: openedPem },
      { label: 'a repeated key header that never closes', value: repeatedHeader },
      { label: 'a bearer scheme before 10 000 credential characters', value: longBearer },
    ];

    for (const { label, value } of hostile) {
      expect(
        elapsedMs(() => void scrub(value)),
        'scrub ' + label,
      ).toBeLessThan(ADVERSARIAL_BUDGET_MS);
      expect(
        elapsedMs(() => void findDeniedRules(value)),
        'findDeniedRules ' + label,
      ).toBeLessThan(ADVERSARIAL_BUDGET_MS);
      expect(
        elapsedMs(() => void containsDenied(value)),
        'containsDenied ' + label,
      ).toBeLessThan(ADVERSARIAL_BUDGET_MS);
    }
  });

  it('still redacts the hostile bearer input it survived', () => {
    // Surviving hostile input is only half the guarantee: the value still has
    // to come back clean.
    const longBearer = BEARER_SCHEME + ' ' + cycle(BEARER_CHARS, 10_000);

    expect(scrub(longBearer)).toBe(BEARER_SCHEME + ' ' + REDACTION_MARKER);
  });

  it('is pure: repeated calls agree and no module state drifts', () => {
    // Detection uses non-global patterns and replacement uses global ones,
    // never the same instance for both. Sharing one would leak `lastIndex`
    // between calls and make every second call disagree with the first - a
    // failure mode that a single-call test cannot see.
    for (const { label, value } of ALL_FIXTURES) {
      const scrubbed = scrub(value);
      const reported = findDeniedRules(value, 'authorization');
      const contains = containsDenied(value, 'authorization');
      const entropy = shannonEntropy(value);

      for (let pass = 0; pass < 5; pass += 1) {
        expect(scrub(value), label + ' pass ' + pass).toBe(scrubbed);
        expect(findDeniedRules(value, 'authorization'), label + ' pass ' + pass).toEqual(reported);
        expect(containsDenied(value, 'authorization'), label + ' pass ' + pass).toBe(contains);
        expect(shannonEntropy(value), label + ' pass ' + pass).toBe(entropy);
      }
    }

    expect([...REDACTION_RULE_IDS]).toEqual(RULE_IDS_AT_LOAD);
  });
});

