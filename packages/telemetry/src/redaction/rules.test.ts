/** Code points of `value`, so lengths are counted the way truncate counts them. */
function codePoints(value: string): string[] {
  return Array.from(value);
}

/** Whether `value` contains a surrogate that lost its pair. */
function hasLoneSurrogate(value: string): boolean {
  return codePoints(value).some((point) => {
    if (point.length !== 1) {
      return false;
    }
    const unit = point.charCodeAt(0);
    return unit >= 0xd800 && unit <= 0xdfff;
  });
}

describe('truncate', () => {
  it('returns a value under the bound unchanged', () => {
    expect(truncate('abcdef', 10)).toBe('abcdef');
  });

  it('returns a value exactly at the bound unchanged', () => {
    // The trap for idempotence: a value already at the bound must not acquire
    // a suffix, or every further call would shorten it again.
    expect(truncate('abcdef', 6)).toBe('abcdef');
  });

  it('shortens a value over the bound to exactly the bound, suffix included', () => {
    const shortened = truncate('abcdefghij', 5);

    expect(codePoints(shortened)).toHaveLength(5);
    expect(shortened.endsWith(TRUNCATION_SUFFIX)).toBe(true);
    expect(shortened).toBe('abcd' + TRUNCATION_SUFFIX);
  });

  it('counts code points, never UTF-16 code units', () => {
    // Four astral characters plus the suffix are five code points but nine
    // code units; counting units would cut this value in half.
    const astral = '\u{1F600}'.repeat(10);
    const shortened = truncate(astral, 5);

    expect(codePoints(shortened)).toHaveLength(5);
    expect(shortened.length).toBe(9);
    expect(shortened).toBe('\u{1F600}'.repeat(4) + TRUNCATION_SUFFIX);
  });

  it('never splits a surrogate pair or emits a lone surrogate', () => {
    const mixed = 'ab' + '\u{1F600}'.repeat(4) + 'cd';

    for (let bound = 1; bound <= codePoints(mixed).length + 2; bound += 1) {
      const shortened = truncate(mixed, bound);

      expect(hasLoneSurrogate(shortened), 'bound ' + bound).toBe(false);
      expect(codePoints(shortened).length, 'bound ' + bound).toBeLessThanOrEqual(bound);
    }
  });

  it('returns an empty string for a bound of zero or less', () => {
    expect(truncate('abc', 0)).toBe('');
    expect(truncate('abc', -1)).toBe('');
    expect(truncate('abc', -1000)).toBe('');
  });

  it('floors a non-integer bound', () => {
    expect(truncate('abcdefgh', 4.9)).toBe(truncate('abcdefgh', 4));
    expect(codePoints(truncate('abcdefgh', 4.9))).toHaveLength(4);
  });

  it('does not truncate at all when the bound is not finite', () => {
    const value = cycle(LOWER_LETTERS, 400);

    expect(truncate(value, Number.POSITIVE_INFINITY)).toBe(value);
    expect(truncate(value, Number.NEGATIVE_INFINITY)).toBe(value);
    expect(truncate(value, Number.NaN)).toBe(value);
  });

  it('takes the bound from its caller and defaults to nothing', () => {
    // The single definition of the preview length lives in
    // ../schema/attributes.ts; this module must not carry a copy of it. A
    // default parameter would report an arity of 1.
    expect(truncate).toHaveLength(2);

    const value = cycle(LOWER_LETTERS, 400);

    expect(codePoints(truncate(value, CALLER_PREVIEW_LENGTH))).toHaveLength(CALLER_PREVIEW_LENGTH);
    expect(codePoints(truncate(value, 10))).toHaveLength(10);
  });

  it('accepts an empty value at any bound', () => {
    expect(truncate('', 10)).toBe('');
    expect(truncate('', 0)).toBe('');
  });
});

