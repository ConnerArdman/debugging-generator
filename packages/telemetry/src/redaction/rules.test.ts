/**
 * Colocated tests for `./rules.ts` — the deny-list vocabulary and the
 * redaction primitives every other layer of the privacy boundary composes.
 *
 * **What this suite owns.** AAP §0.8.3 requires the redaction package to
 * cover "headers, URL params, SQL literals, tokens, `request-key`
 * true-duplicate vs different-parameter cases". The four other rows belong to
 * the suites beside their handlers (`headers.test.ts`, `url.test.ts`,
 * `sql.test.ts`, `request-key.test.ts`); this file owns the **tokens** row —
 * every content-driven credential class `scrub` replaces — plus the
 * primitives those handlers build on: the marker and mask literals, the rule
 * vocabulary, the key-name rule, the entropy heuristic, the detection
 * reporters and `truncate`.
 *
 * **Why every fixture is assembled at runtime.** This file is tracked, and
 * `scripts/check-secrets.mjs` scans tracked content with the same rule
 * classes the module under test implements — `provider-key`, `jwt`,
 * `private-key`, `entropy` and `connection-string` — against an allowlist
 * that names only two development placeholders in six specific files, none of
 * them this one. A realistic credential, PEM block or credentialed connection
 * string pasted here as a literal would therefore fail the commit gate even
 * though it is a test fixture. So no credential prefix, token body or
 * key-file delimiter appears as a contiguous literal below: alphabets are
 * built from character ranges, bodies are generated by cycling those
 * alphabets, and prefixes are joined from fragments through {@link assemble}.
 * The same discipline is why the fixtures also stay out of the test *names*.
 * `rules.ts` itself is written this way, and for the same reason.
 *
 * **Fixtures are inline, deliberately.** Nothing here reads
 * `packages/telemetry/test/fixtures/**`: the curated redacted samples in that
 * directory are a separate deliverable, and a primitive-level suite that
 * cannot run without them would couple the two.
 *
 * **Harness.** The root `vitest.config.ts` collects this file into the
 * `telemetry` project. That project runs under happy-dom with `globals: true`,
 * but `describe`/`it`/`expect` are imported explicitly all the same — the
 * convention across this monorepo's suites — and nothing here touches a
 * `document`: the module under test is pure and environment-independent.
 * `node:fs`, `node:path` and `node:url` are imported for the module-contract
 * guard at the bottom of the file, which is permitted here because a test file
 * is never a tsup or esbuild entry point (see that suite's own commentary).
 */

