/**
 * The `panel.generated` message: the product's payoff crossing a process
 * boundary.
 *
 * One payload lives here, and it carries the thing the whole pipeline exists to
 * produce — a validated, normalized panel specification — from the local
 * coordination service to the two surfaces that draw it: the Chrome DevTools
 * panel and the editor's view. Everything upstream of this frame is work the
 * developer cannot see: a question understood, a codebase indexed, an
 * instrumentation plan applied and reverted, telemetry captured from three
 * tiers, a trace correlated, an analysis written against evidence. This message
 * is where that becomes a screen.
 *
 * ## The hop this schema governs
 *
 * ```text
 * the panel-generation stage, which validates and normalizes a specification
 *   → the session store, which keeps every generation as its own row
 *   → this WebSocket message, `panel.generated`, broadcast to the session's
 *     clients
 *   → the MV3 background service worker, which forwards it over a runtime port
 *     to the DevTools panel page, and the editor's extension host, which
 *     forwards it to its webview
 *   → the shared renderer's host component, which draws the summary and then
 *     each node of the layout
 * ```
 *
 * Both destinations receive the same frame, and the service is the only sender:
 * a panel is generated by the pipeline, never composed by a user interface, and
 * a client that wants one it has not received asks for it over HTTP
 * (`GET /sessions/:id/panel`, `GET /sessions/:id/panels/:panelId`) rather than
 * announcing one on this type.
 *
 * ## Deliberately thin, because the panel language is rich
 *
 * Three fields, and only one of them has structure. That asymmetry is the
 * design: everything that makes one generated panel differ from another — the
 * visualization node vocabulary, each node's data query, the summary's
 * separation of observed facts from likely causes, the node catalog the
 * validator and the renderer's component registry are both keyed by — is owned
 * by `@debuggen/panel-schema` and inherited here by **embedding its schema**,
 * not by restating any part of it. A second definition of a shape that crosses a
 * process boundary is the defect the requirements name outright (AAP §0.2.3,
 * §0.9.1), and a permissive passthrough in its place would be worse than a
 * duplicate: it would let a malformed document reach a renderer that has no
 * component for it, which is a blank area on screen instead of a rejected frame.
 *
 * What travels here is the **internal** specification — the normalized document
 * a validator has already accepted. The authoring shape a model produces
 * (`PanelSpecInput`, where query fields may sit flat on a node and a summary may
 * be a bare string) is not a wire type and must never appear in a frame: the
 * pipeline parses model output against that shape, normalizes it
 * deterministically, validates the result, and only then does a panel become
 * something this message can carry (AAP §0.2.3, §0.5.3).
 *
 * ## What this schema does not decide
 *
 * - **Whether the panel is true of the capture.** Semantic validation — that
 *   every cited evidence reference and every filtered trace exists in the
 *   capture — belongs to `packages/panel-schema/src/semantic.ts` and to the
 *   service that holds the capture. This package has no capture, so the check
 *   cannot be made here, and a weaker copy of it would be a contract in a place
 *   that cannot enforce it.
 * - **Whether the two ids agree.** See {@link panelGeneratedPayloadSchema}.
 * - **Whether the panel answers the question.** That is the analysis's business,
 *   and the summary's fact and hypothesis types are where the distinction
 *   between an observation and an inference is expressed.
 *
 * ## Panel *data* does not travel on this message
 *
 * A generated panel is a description of views, not the rows inside them. Every
 * visualization node except the source-link leaf carries a data query that the
 * renderer's host resolves through `POST /sessions/:id/panel-data`, whose
 * request body and result union live in `../http.ts`. That split is what keeps
 * this frame small enough to broadcast on every regeneration and lets a panel
 * page a large result set, filter it and re-sort it without the service
 * regenerating anything.
 *
 * **Nobody may enrich this payload with rows.** A field carrying spans, renders,
 * requests or query groups alongside the specification would duplicate the
 * panel-data contract, make the frame unbounded in the size of a capture, and
 * put the same numbers on two paths that can disagree. `z.strictObject` below
 * is what makes that a rejected frame rather than a silently stripped field.
 *
 * ## Module rules
 *
 * Named exports only, no default export, and no import-time side effect: the
 * manifest declares `sideEffects: false`, so everything below is a declaration.
 * No `.transform()`, `.coerce`, `.default()` or `.catch()` appears in this
 * package — a schema validates, it never rewrites — which matters more here than
 * anywhere else in the folder: this document is written once, persisted as JSON,
 * and then crosses a WebSocket, a `chrome.runtime` port and the editor's webview
 * boundary, so it is parsed several times on its way to a screen. A schema that
 * rewrote a value on the way through would make the panel a developer sees
 * differ from the panel the store holds, and each hop would compound the
 * difference. Parsing here is therefore value-for-value faithful and idempotent;
 * two nuances belong to the embedded document rather than to this payload and
 * are worth knowing at this boundary: the parsed object's **key order** follows
 * the declaration order of the owner's schema rather than the order a producer
 * happened to serialise, and the summary's two lists are the one place the owner
 * fills an omitted key, deliberately, so that every consumer can iterate without
 * branching on `undefined` — a normalized specification carries both already, so
 * a document that reaches this frame from the pipeline is unaffected. This
 * module imports no
 * sibling in this folder; the folder registry merges
 * {@link PANEL_MESSAGE_PAYLOADS} with its siblings' maps, and the envelope —
 * which nothing in this folder may import — builds the discriminated union from
 * that registry.
 *
 * @example
 * ```ts
 * const parsed = parsePanelGeneratedPayload(message.payload);
 *
 * if (parsed.ok) {
 *   const { panelId, panel } = parsed.value;
 *   // A deterministically assembled panel is a success, drawn under a banner.
 *   cache.set(panelId, panel);
 *   render(panel, { fallback: panel.meta?.fallback === true });
 * }
 * ```
 */

import { z } from 'zod';

import { err, ok } from '@debuggen/shared';
import type { DebuggenError, Result } from '@debuggen/shared';
import { panelSpecSchema } from '@debuggen/panel-schema';
import type { PanelSpec } from '@debuggen/panel-schema';

import { protocolParseError } from '../version.js';

// ---------------------------------------------------------------------------
// Section A — the id primitive
// ---------------------------------------------------------------------------

/**
 * The longest id this folder accepts in a payload field.
 *
 * Folder-canonical: every message module bounds an id the same way, so a frame
 * that arrived with a megabyte where a session id belongs is refused on a length
 * check rather than carried into a store lookup, a log line or a cache key. The
 * ids this product mints are twenty characters — a short kind prefix, an
 * underscore and a generated suffix — so sixty-four is generous room for an id
 * from an older build while still refusing the class of value that cannot be one
 * at all.
 *
 * Module-private, like its equivalents in the sibling modules: `../version.ts`
 * exports no id primitive, and this folder's registry re-exports every public
 * name in it, so a constant each domain module needs stays local rather than
 * colliding with a sibling's copy under one exported name.
 */
const MAX_ID_LENGTH = 64;

/**
 * An opaque identifier as a payload field: a non-empty string of at most
 * {@link MAX_ID_LENGTH} characters.
 *
 * Deliberately **not** the prefixed form `@debuggen/shared`'s id module mints.
 * That module owns the prefix vocabulary and the id grammar; re-deriving either
 * here would be a second definition of a shape this package does not own, and it
 * would reject a panel read back from a store written by a build whose prefixes
 * differed — turning a reopened session into an unparseable row for no gain. The
 * transport makes the one check a transport can make, that the field is a string
 * of plausible length, and identity is resolved where the id is looked up.
 *
 * Note what this leaves to the embedded specification: the panel's own `id`,
 * `sessionId` and `supersedes` are bounded and shaped by `@debuggen/panel-schema`
 * under its own, slightly more generous ceiling, because a stored document must
 * stay readable. This schema does not reach into the document to re-check them.
 */
const idSchema = z
  .string()
  .min(1, { error: 'expected a non-empty identifier' })
  .max(MAX_ID_LENGTH, {
    error: `expected an identifier of at most ${String(MAX_ID_LENGTH)} characters`,
  });

// ---------------------------------------------------------------------------
// Section B — the payload
// ---------------------------------------------------------------------------

/**
 * The payload of `panel.generated`: which session the panel answers, which panel
 * it is, and the panel itself.
 *
 * `z.strictObject`, so an unrecognised key is a rejection rather than a silently
 * stripped field. The two producers that strictness turns away are both
 * plausible: one that attached captured rows to the frame (see the module
 * header), and one that invented a presentation dimension the renderer will
 * never read. Without the strict object both would be accepted and then fail on
 * screen — a panel that claims to carry something nothing draws is worse than a
 * refused frame, because nobody is told.
 *
 * ## Why `panelId` sits beside the specification's own `id`
 *
 * They are the same value, and they are here for different reasons:
 *
 * - `panelId` is the **routing and caching key** both user interfaces use. A
 *   panel page keeps its rendered panels by this key, a follow-up regeneration
 *   arrives under a new one, and it is the same value that appears in the path
 *   of `GET /sessions/:id/panels/:panelId` — so a client can re-request exactly
 *   what it was handed without first parsing the document to find out what to
 *   ask for. Reading it off the envelope's payload rather than out of the
 *   embedded document is what lets a receiver route, deduplicate or discard a
 *   frame before it commits to the specification's contents.
 * - `panel.id` is the **stored artifact's identity**, carried inside the
 *   document so that a specification read from anywhere — a store row, a
 *   fixture, a file — knows which panel it is without its envelope.
 *
 * The service must send the same value in both places, and **enforcing that
 * equality is not this schema's job.** A cross-field refinement would make this
 * module an arbiter of a behaviour rather than a shape: it is the sender's
 * invariant, checked where the panel is stored and broadcast; it would vanish
 * from any JSON Schema rendered from this shape; and a mismatch is a service bug
 * whose honest outcome is a service-side assertion, not a frame the receiver
 * cannot explain. This folder validates shape.
 *
 * ## What versioning and fallback do to this payload: nothing
 *
 * Both ride **inside** the specification, which is why this payload needs no
 * further key:
 *
 * - A follow-up question does not overwrite the panel that answered the first
 *   one. Whether the answer is regenerated from evidence already held or from a
 *   fresh capture, the result is stored as the next `panelVersion` with
 *   `supersedes` naming the panel it replaces, and this same message type
 *   carries both (AAP §0.4.2). A receiver that wants to show that the answer
 *   moved on reads them off `panel`.
 * - A panel assembled deterministically from the capture's aggregates, because a
 *   generated one could not be validated, is marked `meta.fallback` and is a
 *   **success**: it travels on this message and never on the `error` frame, and
 *   the renderer draws it under a visible fallback banner so the developer knows
 *   the views below are a deterministic summary rather than an answer to their
 *   question (AAP §0.5.5). Mapping such a frame to an error would present honest
 *   degradation as a failure and leave the developer with nothing.
 */
export const panelGeneratedPayloadSchema = z.strictObject({
  /** The session whose question this panel answers. */
  sessionId: idSchema,

  /**
   * The generated panel's id, as the frame's routing and caching key.
   *
   * The same value as `panel.id`; see the note above for why both exist and why
   * their agreement is the sender's invariant rather than this schema's.
   */
  panelId: idSchema,

  /**
   * The panel itself, as the single shared specification shape.
   *
   * The imported `panelSpecSchema` used as a field with no wrapper and no second
   * pass over its members. Zod keeps refinements inside the schema, so nesting
   * it here runs the owner's own checks — the format version, the bounded title,
   * the summary whose observed facts each cite evidence, the closed node union
   * with its data queries — and reports their issues under the full path
   * (`panel.layout[2].query.source`, `panel.summary.observed[0].evidence`),
   * which is exactly what a producer needs to fix its side.
   *
   * A node type outside the catalogued vocabulary is therefore rejected here,
   * inherited rather than restated, which is the point of embedding the real
   * schema instead of accepting a record: the renderer's component registry is
   * keyed by the same catalog the validator consumes, so a type with no
   * component cannot reach a surface and leave a blank area.
   */
  panel: panelSpecSchema,
});

/**
 * The `panel.generated` payload.
 *
 * Inferred from {@link panelGeneratedPayloadSchema} rather than declared beside
 * it, so the validator and the type are one statement. `panel` is what the
 * imported specification schema parses and is assignable to the `PanelSpec`
 * interface of `@debuggen/panel-schema` — both proved at compile time in
 * Section D — which is what lets a receiver pass the parsed value straight into
 * the renderer's host and the store without a cast or a copy.
 */
export type PanelGeneratedPayload = z.infer<typeof panelGeneratedPayloadSchema>;

// ---------------------------------------------------------------------------
// Section C — non-throwing parser and the folder registry
// ---------------------------------------------------------------------------

/**
 * The hint offered when a `panel.generated` payload fails validation.
 *
 * A single statement of the contract, free of any rejected data: it is forwarded
 * verbatim by `DebuggenError.toPayload()` and therefore crosses the wire.
 */
const PANEL_GENERATED_HINT =
  'A panel.generated payload carries exactly three fields: the session id, the generated panel id, and a panel that satisfies the normalized panel specification schema of @debuggen/panel-schema. Authoring-shape output must be normalized and validated before it is broadcast, and captured rows are fetched separately through the panel-data route rather than attached here.';

/**
 * Validates an unknown value as a {@link PanelGeneratedPayload}, without
 * throwing.
 *
 * This is how a frame that arrived over the WebSocket, or a payload replayed
 * from the store when a session is reopened, becomes a typed payload. Both
 * receivers parse rather than destructure: the DevTools panel's copy has
 * travelled through a browser extension's port, and the editor's copy through a
 * webview boundary.
 *
 * Non-throwing is a requirement rather than a preference. A rejected panel frame
 * has a defined outcome — the surface keeps the panel it already had and reports
 * that this one could not be shown — and that outcome is reached by inspecting a
 * result, not by unwinding a message-handling loop that other sessions' frames
 * also travel through.
 *
 * **The failure carries the shape of the failure and none of the data that
 * caused it.** `protocolParseError` renders the issue list through this
 * package's one sanctioned formatter: field paths, issue codes and
 * schema-declared metadata, never a rejected value. That rule earns its keep
 * precisely here, because a panel is the most sensitive document this protocol
 * moves — its summary states observed facts drawn from the developer's own
 * runtime, its nodes name components and redacted statements, and its prose is
 * model-authored. A validation error is raised far below the redaction layer and
 * far below the outbound model guard, so neither can rescue a value that leaked
 * into it, and this error is logged, may be persisted with the session, and is
 * shown in both user interfaces (AAP §0.5.2).
 *
 * @param value Any value believed to be a `panel.generated` payload.
 * @returns `ok(payload)` with the validated payload, or `err(error)` describing
 * the shape of the failure.
 *
 * @example
 * ```ts
 * const parsed = parsePanelGeneratedPayload(frame.payload);
 * if (!parsed.ok) {
 *   logger.warn('refused panel.generated', { reason: parsed.error.message });
 *   return;
 * }
 * ```
 */
export function parsePanelGeneratedPayload(
  value: unknown,
): Result<PanelGeneratedPayload, DebuggenError> {
  const parsed = panelGeneratedPayloadSchema.safeParse(value);

  if (parsed.success) {
    return ok(parsed.data);
  }

  return err(
    protocolParseError(
      'PROTOCOL_INVALID_MESSAGE',
      'Invalid panel.generated payload',
      parsed.error.issues,
      PANEL_GENERATED_HINT,
    ),
  );
}

/**
 * This module's contribution to the folder registry: the payload schema of
 * `panel.generated`, under its wire name.
 *
 * The folder's registry module merges this map with the other domain modules'
 * maps into the single `type → payload schema` table, and the envelope maps over
 * that table to build the discriminated union every frame is validated against.
 * The key is verbatim from AAP §0.4.2 and is one of the message names the
 * product's requirements fix character for character, so it is written once,
 * here, and referenced everywhere else.
 *
 * Exactly one key: the HTTP reads of a stored panel (`GET /sessions/:id/panel`,
 * `GET /sessions/:id/panels/:panelId`) and the panel-data query are routes
 * rather than message types, and they belong to `../http.ts`.
 *
 * Frozen because it is a module-level table the envelope reads on every parse: a
 * mutation would redefine what the whole process accepts on the wire.
 */
export const PANEL_MESSAGE_PAYLOADS = Object.freeze({
  'panel.generated': panelGeneratedPayloadSchema,
} as const);

// ---------------------------------------------------------------------------
// Section D — the embedded specification keeps its type, proved at compile time
// ---------------------------------------------------------------------------

/**
 * `true` when `A` and `B` are mutually assignable, `false` otherwise.
 *
 * The tuple wrappers stop a naked `never` or a union from distributing, so this
 * answers about the types as written rather than about their members.
 */
type MutuallyAssignable<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false;

/**
 * `true` when `A` is assignable to `B`, `false` otherwise, with the same
 * distribution guard.
 */
type AssignableTo<A, B> = [A] extends [B] ? true : false;

/**
 * Accepts `true` and nothing else: instantiating it with `false` is a compile
 * error (TS2344), which is what turns a type comparison into an assertion.
 */
type AssertTrue<T extends true> = T;

/**
 * Compile-time proof that the `panel` field is the output of the **imported**
 * specification schema, and that a parsed payload's panel is usable everywhere a
 * `PanelSpec` is expected.
 *
 * Three claims, in the order a reader should check them:
 *
 * 1. the field's type is exactly what `panelSpecSchema` parses, so the schema was
 *    embedded rather than restated, wrapped or replaced by a record;
 * 2. that type is assignable to the imported `PanelSpec` interface, so the
 *    parsed value can be handed straight to the renderer's host, to the store
 *    and to the editor's view — the owner declares that interface with
 *    `readonly` members and `readonly` arrays, which a schema's parsed output
 *    satisfies without being identical to, so this direction is the one that can
 *    be asserted and the one that matters to a consumer;
 * 3. the field is not `unknown` or `any`. Either of those would be mutually
 *    assignable with `unknown`, so requiring that comparison to be `false` is
 *    what rules out a permissive passthrough — the failure mode this whole
 *    section exists to prevent, because a document that parsed as `unknown`
 *    reaches a renderer with no component for it and draws a blank area instead
 *    of being refused on the wire.
 *
 * This resolves to `true`, and it is the assertion rather than the value that
 * matters: a future edit that widened the field would instantiate
 * {@link AssertTrue} with `false` and fail to compile here, in the module that
 * made the mistake, rather than at the first surface that trusted it.
 *
 * It is exported because a type alias nothing references is a compile error
 * under this repository's `noUnusedLocals`, and because a reader of the emitted
 * declarations can see the guarantee stated. Nothing consumes it at runtime;
 * there is nothing to consume.
 *
 * @internal
 */
export type PanelSpecTypePreserved = AssertTrue<
  MutuallyAssignable<PanelGeneratedPayload['panel'], z.infer<typeof panelSpecSchema>> extends true
    ? AssignableTo<PanelGeneratedPayload['panel'], PanelSpec> extends true
      ? MutuallyAssignable<PanelGeneratedPayload['panel'], unknown> extends true
        ? false
        : true
      : false
    : false
>;
